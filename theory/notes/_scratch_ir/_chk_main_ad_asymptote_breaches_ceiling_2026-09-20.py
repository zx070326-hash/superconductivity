"""
接上一脚本：曲率在实验与 AD 之间**不可分辨**（0.61σ）。
那么「天花板」相对 AD 还有没有**可检验的独立内容**？有，且位置很具体：

    AD75 的**强耦合渐近常数**破掉天花板。

  λ→∞ 时 f₁ → √(λ/Λ₁)、f₂ → ω̄₂/ω_log、指数 → exp[−1.04/(1−0.62μ*)]
  ⟹ Tc_AD → [exp(−1.04/(1−0.62μ*)) / (1.2√Λ₁)] · √λ · ω̄₂
  而天花板给 Tc ≤ C_∞ √λ ω̄₂，C_∞ = 0.1827262477
  ⟹ 𝔣_AD(∞) = 该系数 / C_∞ ，若 > 1 则 **AD 在强耦合端违反天花板**。

本脚本：
  A  解析渐近常数（含 μ* 依赖），与 C_∞ 比
  B  𝔣_AD(λ) 全程曲线：何时越过 1？逼近渐近值有多慢？
  C  **可分辨性预算**：要在数据上把「天花板」与「AD」分开，需要多大的 λ / 多少行？
     —— 这才是曲率检验之后真正剩下的判别性问题。

主会话 2026-09-20，从零。
"""
import sys
sys.stdout.reconfigure(encoding="utf-8", errors="replace")
import numpy as np

C_INF = 0.1827262477

def tc_ad(lam, wlog, wb2, mu):
    r = wb2 / wlog
    L1 = 2.46 * (1 + 3.8 * mu); L2 = 1.82 * (1 + 6.3 * mu) * r
    f1 = (1 + (lam / L1) ** 1.5) ** (1.0 / 3.0)
    f2 = 1 + (r - 1) * lam ** 2 / (lam ** 2 + L2 ** 2)
    return (wlog / 1.2) * np.exp(-1.04 * (1 + lam) / (lam - mu * (1 + 0.62 * lam))) * f1 * f2

print("=" * 98)
print("A  AD75 的强耦合渐近常数 vs 天花板常数 C_∞")
print("=" * 98)
print(f"  C_∞ = {C_INF:.10f}   (Tc ≤ C_∞·√(λ⟨ω²⟩) = C_∞·√λ·ω̄₂)")
print(f"  {'μ*':>8}{'AD 渐近常数':>16}{'/ C_∞':>12}{'判定':>22}")
for mu in [0.0, 0.05, 0.10, 0.13, 0.15]:
    L1 = 2.46 * (1 + 3.8 * mu)
    const = np.exp(-1.04 / (1 - 0.62 * mu)) / (1.2 * np.sqrt(L1))
    print(f"  {mu:>8.2f}{const:>16.7f}{const/C_INF:>12.5f}"
          f"{('  **违反天花板 %+.2f%%**' % ((const/C_INF-1)*100)) if const > C_INF else '  在天花板内':>22}")
print("""
  ⟹ μ*=0 处 AD 的渐近常数 = 0.1878（比 C_∞ 高 2.8%）⟹ **AD 在 λ→∞ 破天花板**。
     μ* 增大时 Λ₁ 变大、指数被压，AD 渐近常数下降 ⟹ 违反只在小 μ* 端。
     这与仓库既有 memory「AD 渐近常数 0.1877954 比 C_∞ 高 2.77%」一致（独立重算）。""")

print()
print("=" * 98)
print("B  𝔣_AD(λ) 全程：何时越过 1？逼近有多慢？（固定谱形 ω̄₂/ω_log = 中位 1.292）")
print("=" * 98)
r_med = 1.0 / 0.7742          # AD75 中位 ω_log/ω̄₂ = 0.7742
wlog = 100.0; wb2 = wlog * r_med
print(f"  {'λ':>8}" + "".join(f"{'μ*=%.2f' % m:>12}" for m in [0.0, 0.10, 0.13]))
for lam in [1, 2, 2.59, 4, 6, 10, 20, 50, 100, 1000]:
    row = f"  {lam:>8.2f}"
    for mu in [0.0, 0.10, 0.13]:
        f = tc_ad(np.array([lam]), wlog, wb2, mu)[0] / (C_INF * np.sqrt(lam) * wb2)
        row += f"{f:>12.4f}" + ("*" if f > 1 else " ")
    print(row)
print("  （* = 破天花板）")

# 越过 1 的 λ
from scipy.optimize import brentq
print()
for mu in [0.0, 0.05, 0.10, 0.13]:
    g = lambda l: tc_ad(np.array([l]), wlog, wb2, mu)[0] / (C_INF * np.sqrt(l) * wb2) - 1.0
    try:
        if g(3) * g(5000) < 0:
            lc = brentq(g, 3, 5000)
            print(f"  μ*={mu:.2f}: 𝔣_AD 在 λ* = {lc:.1f} 处越过 1   （AD75 表内最大 λ = 2.59）")
        else:
            print(f"  μ*={mu:.2f}: 𝔣_AD 在 λ∈[3,5000] 内**不**越过 1（渐近值 "
                  f"{np.exp(-1.04/(1-0.62*mu))/(1.2*np.sqrt(2.46*(1+3.8*mu)))/C_INF:.4f}）")
    except Exception as e:
        print(f"  μ*={mu:.2f}: {e}")

print()
print("=" * 98)
print("C  「天花板 vs AD」的冲突区在哪？——注意这里**极易问错问题**")
print("=" * 98)
print("""  ⚠ 自查（本脚本初版 C 段算错了对象，在此订正并保留记录）：
     初版印的是「𝔣_AD 到 1 的 log 距」，并按回归标准误判「64σ 可分辨」。**那是无意义的量。**
     天花板是**单边不等式** `𝔣 ≤ 1`，它**不做点预测**；AD 预测 𝔣=0.57 与天花板 `𝔣≤1`
     **毫不冲突**。「离 1 有多远」既不是分歧，也不可被证伪。
     按仓库单边界方向规则：`𝔣 ≤ 1` 只能被 `𝔣 > 1` 证伪，不能被任何 `𝔣 < 1` 的观测「证实」。

  ⟹ 正确的问题只有一个：**在哪个 (λ, μ*) 上 AD 预言 𝔣 > 1（即 AD 与定理真冲突）？**""")

def f_ad(lam, mu):
    return tc_ad(np.array([lam]), wlog, wb2, mu)[0] / (C_INF * np.sqrt(lam) * wb2)

# 渐近常数 = C_∞ 的 μ* 临界值
gmu = lambda m: np.exp(-1.04 / (1 - 0.62 * m)) / (1.2 * np.sqrt(2.46 * (1 + 3.8 * m))) - C_INF
mu_c = brentq(gmu, 0.0, 0.2)
print(f"\n  AD 渐近常数 = C_∞ 的临界 μ* : **μ*_c = {mu_c:.5f}**")
print(f"    μ* < {mu_c:.4f} ⟹ AD 在足够大的 λ 上破天花板；μ* > {mu_c:.4f} ⟹ AD **永不**破。")
print(f"\n  {'μ*':>8}{'渐近 𝔣_AD(∞)':>16}{'破天花板的 λ 门槛':>22}")
for mu in [0.0, 0.01, 0.02, 0.03, mu_c, 0.05, 0.08, 0.10, 0.13]:
    fa = np.exp(-1.04 / (1 - 0.62 * mu)) / (1.2 * np.sqrt(2.46 * (1 + 3.8 * mu))) / C_INF
    if fa > 1:
        g = lambda l: f_ad(l, mu) - 1.0
        lo, hi = 1.0, 1e9
        thr_s = f"λ > {brentq(g, lo, hi):.1f}" if g(lo) * g(hi) < 0 else "（全程 >1）"
    else:
        thr_s = "**不存在**"
    print(f"  {mu:>8.4f}{fa:>16.4f}{thr_s:>22}")

print(f"""
  ⟹ **AD75 与天花板的冲突区 = {{μ* < {mu_c:.3f}}} ∩ {{λ ≳ 30}}。**
     AD75 自己 29 行的 μ* ∈ [0.081, 0.117]，全部 **远在 μ*_c 之上**；
     实际材料的 μ* 没有低于 0.05 的。⟹ **在物理区域，AD 与天花板从不冲突。**""")


# AUDIT, this session, at iv.dps = 30 (prec = 103 bits), every iv primitive
# reachable from any M-series bound, tested against a 700-bit mp reference
# (probes: _scratch_ir/m5_ivsound.py, m5_ivpi.py):
#
#   iv.atan2   UNSOUND.  2502/40000 random and 1429/20000 systematic
#              operands NOT enclosed; worst absolute excursion 1.41e-32
#              (~0.2 ulp).  Cause: mpf_atan2 computes mpf_atan(mpf_div(y, x,
#              prec+4), prec+4) with round-to-NEAREST internally and directs
#              only the FINAL rounding, so the directed endpoints are
#              directed roundings of an already-perturbed value.
#              (Independently found by the segment C-I agent, which measured
#              ~9.4% of 200k pairs against a 600-bit reference.)
#   iv.log     SOUND.  0 / 120000 not enclosed, three operand shapes
#              including exactly the log(1+s^2) form M4 uses.
#   iv.sqrt    SOUND.  0 / 40000.  (mpi_sqrt directs the rounding of the
#              root itself.)
#   iv.pi      SOUND.  Endpoints are bit-identical to
#              libmp.mpf_pi(prec, round_floor / round_ceiling).
#              TRAP FOR ANYONE REPRODUCING THIS: mp.pi is a LAZY constant
#              that re-evaluates at whatever mp.prec is current when you
#              compare it.  Force it with `+mp.pi` at the reference
#              precision first, or the probe reports a false failure.
#
# M5's own 18 objects use NO transcendental at all -- the integrand, the
# tail charts, the family sups and both outer integrands are rational in
# sigma and s.  The contamination enters only through M3's assembly, at one
# choke point, `p4_cii_m3_interval.py:99  atan_iv(y) = iv.atan2(y, 1)`,
# which feeds atan_jet / d_jet / Lo_jet / theta_star / beta.  Replacing that
# single function closes every arctan path in M3, M4 and M5 at once; see
# `install_certified_primitives()`.
#
# THE REPLACEMENT uses + - * / and sqrt ONLY.
#   1. Argument reduction by the exact half-angle identity
#          atan(t) = 2 atan( t / (1 + sqrt(1 + t^2)) )
#      applied until the argument is <= 2^-4.  From any t >= 0 this takes at
#      most ~8 steps (one step maps [1,inf) into [0.414, 1)).
#   2. The alternating series atan(u) = sum (-1)^n u^(2n+1)/(2n+1), with the
#      alternating-series remainder theorem as a two-sided enclosure:
#      for 0 <= u < 1 the tail after N terms is bounded in absolute value by
#      the first omitted term, u^(2N+1)/(2N+1).  With u <= 2^-4 and N = 20
#      that is <= 2^-164/41 ~ 3e-52, far below the 1e-31 of prec 103.
#   3. Multiply back by 2^k.
# Every step is +,-,*,/ or sqrt on intervals, so the result is an enclosure
# by construction; `check_certified_atan` then verifies it against a 700-bit
# reference.
_ATAN_N = 20          # terms of the alternating series
_ATAN_RED = 1.0 / 16  # reduce until the argument is at most this


def _iv_pt(v):
    """Degenerate interval at an endpoint.  `ivmpf.a` / `.b` already return
    a DEGENERATE ivmpf in mpmath 1.3.0, so this is mostly a no-op; it also
    accepts a raw mp.mpf."""
    if hasattr(v, '_mpi_'):
        return v
    return iv.make_mpf((v._mpf_, v._mpf_))


def iv_atan_nn(t, nterms=None):
    """Certified arctan of an interval t with t.a >= 0.  + - * / sqrt only.

    `nterms` exists so the SUITE can drive the series at a term count where
    the truncation is resolvable.  At the shipped _ATAN_N = 20 the remainder
    is ~3e-52, far below the prec-103 rounding width ~1e-31, so no check that
    only looks at the shipped configuration can tell the two-sided remainder
    pad from no pad at all -- deleting it changes not one endpoint bit.
    `check_certified_atan` therefore exercises small nterms, where dropping
    or one-siding the pad breaks containment immediately.

    A WIDE input is split into its endpoints rather than being fed to the
    half-angle recursion.  The recursion is sound on a wide interval but
    useless -- dependency error gives iv_atan_nn([0,1]) -> [-1.7e-50, 1.0] --
    and for t.b >~ 1e18 it does not terminate inside the 64-step guard at all.
    Since arctan is increasing, enclosing endpoint by endpoint is both valid
    and tight, so the degenerate-input precondition is DISCHARGED here instead
    of being left to the caller.  (Reaching the recursion with a wide interval
    was possible before: `iv_atan_nn(2*T/(1-T**2))` is non-degenerate even for
    degenerate T, because outward rounding widens it by an ulp.)"""
    assert t.a >= 0, t
    N = _ATAN_N if nterms is None else nterms
    if t._mpi_[0] != t._mpi_[1]:
        return iv.mpf([iv_atan_nn(_iv_pt(t.a), nterms).a,
                       iv_atan_nn(_iv_pt(t.b), nterms).b])
    k = 0
    while t.b > _ATAN_RED:
        t = t / (1 + iv.sqrt(1 + t ** 2))
        k += 1
        assert k < 64, "arctan argument reduction did not terminate"
    u2 = t ** 2
    acc = iv.mpf(0)
    for n in range(N - 1, -1, -1):             # Horner, alternating
        acc = iv.mpf(1) / (2 * n + 1) - u2 * acc
    s = t * acc
    rem = (t ** (2 * N + 1) / (2 * N + 1)).b
    s = s + iv.mpf([-rem, rem])
    return s * (2 ** k)


def iv_atan(x):
    """Certified arctan on any interval (arctan is increasing, so the
    enclosure is obtained endpoint by endpoint)."""
    a, b = _iv_pt(x.a), _iv_pt(x.b)
    lo = iv_atan_nn(a) if a.a >= 0 else -iv_atan_nn(-a)
    hi = iv_atan_nn(b) if b.a >= 0 else -iv_atan_nn(-b)
    return iv.mpf([lo.a, hi.b])


def atan_iv_certified(y):
    """Drop-in replacement for M3.atan_iv (which is iv.atan2(y, 1))."""
    return iv_atan(y)


PI_IV = 4 * iv_atan_nn(iv.mpf(1))      # self-contained; does not use iv.pi


# ---- rigorous Theta* (M3's theta_star_iv is NOT an enclosure) --------------
# M3 computes Theta* = max_{s>=0} (log(1+s^2) + 2 s atan s) / (2(1+s^2)) by
# bisecting N(s) = 0 at mp.dps=40 for 150 rounds and then returning
#     [float(val) - float(b-a), float(val) + float(b-a)] ,  b-a ~ 2^-150,
# i.e. a float64 value with a 1e-45 halo.  The float64 conversion alone
# perturbs Theta* ~ 0.5 by up to ~3e-17, twenty-five orders larger than the
# halo, so the returned interval need not contain Theta*.  (M3's three other
# compute-in-mp-then-cast sites -- exact_sums_iv, V_FPP_iv, Z3H_IV -- pad by
# 1e-12/1e-13 and are sound; only this one ties its margin to the bisection
# width instead of to the arithmetic.)
#
# M5 replaces it with an interval branch-and-bound, which additionally needs
# NO monotonicity input, so it also discharges M3's appeal to an unrecorded
# "N decreasing, single root" proof.  Tail: for s >= S0 >= 2,
#     Theta(s) <= log(1+s^2)/(2(1+s^2)) + pi/(2 s)
#              <= log(1+S0^2)/(2(1+S0^2)) + pi/(2 S0) ,
# both terms decreasing in s (the first for s >= 2).
THETA_S0 = 64.0


def theta_iv(S):
    """Theta(s) on an interval S >= 0 -- certified arctan + audited iv.log."""
    s2 = S ** 2
    return (iv.log(1 + s2) + 2 * S * iv_atan(S)) / (2 * (1 + s2))


def dtheta_iv(S):
    """Theta'(s) = N(s)/(1+s^2)^2 with N(s) = 2s + (1-s^2) atan s
    - s log(1+s^2).  (Differentiate Theta and simplify; N is exactly the
    function M3 bisects, which is why M3's root-finding and this agree on the
    argmax.)  Used only for the centered form below."""
    s2 = S ** 2
    return (2 * S + (1 - s2) * iv_atan(S) - S * iv.log(1 + s2)) / (1 + s2) ** 2


def theta_ub(a, b):
    """Upper bound for Theta on [a, b], as the INTERSECTION of the direct
    interval evaluation with the centered (mean-value) form
        Theta([a,b])  subset  Theta(m) + Theta'([a,b]) * ([a,b] - m).
    Both are rigorous; the centered one converges quadratically in the box
    width near a critical point, where the direct one is only linear.  Without
    it the branch-and-bound stalls at a width of ~2e-8 for the silly reason
    that O(h) dependency error, not the geometry of the maximum, sets the
    resolution -- it needs ~15000 live boxes to get there and then exhausts
    its budget."""
    box = iv.mpf([a, b])
    direct = mp.make_mpf(theta_iv(box)._mpi_[1])
    m = 0.5 * (a + b)
    cen = mp.make_mpf(
        (theta_iv(iv.mpf(m)) + dtheta_iv(box) * (box - iv.mpf(m)))._mpi_[1])
    # exact mp.mpf, not a degenerate ivmpf: `ivmpf > mpf` evaluates to None
    # (falsy) when the interval OVERLAPS the scalar, and in a pruning
    # branch-and-bound a falsy comparison discards a box that should have been
    # split.  Degenerate values compare fine today; this removes the standing
    # obligation to prove they stay degenerate.
    return direct if direct < cen else cen


def theta_star_certified(s0=THETA_S0, nb=20000, tol=1e-28, rounds=200):
    """Rigorous enclosure of Theta* = max_{s>=0} Theta(s), plus the argmax
    box midpoint (M3's build_theta_star returns that as S_STAR; nothing in
    the assembly reads it, but the signature has to match).

    Pruning branch-and-bound.  `best` is always a VERIFIED lower bound on
    Theta* (the lower endpoint of the enclosure of Theta at an actual point),
    so any box whose enclosure upper bound is <= best provably cannot contain
    the maximiser and is discarded -- that is what keeps the box budget on the
    boxes that matter.  On exit
        Theta*  in  [ best , max(best, max over SURVIVING boxes of ub) ]
    because the discarded boxes have sup <= best and the tail region is
    handled by `tail` (asserted strictly below `best`, i.e. non-binding).
    No monotonicity, no root-finding, no appeal to Theta' -- which also
    discharges M3's citation of an unrecorded "N decreasing, single root"
    proof."""
    # The tail majorant below is only a MAJORANT because both of its terms are
    # decreasing on [s0, oo); log(1+s^2)/(2(1+s^2)) decreases iff 1+s^2 > e,
    # i.e. s > 1.3110.  Asserted rather than assumed: a caller passing s0 = 1
    # would otherwise get a silently invalid bound.
    assert s0 >= 2.0, "Theta tail majorant needs s0 >= 2 (got %r)" % (s0,)
    S0 = iv.mpf(s0)
    tail = (iv.log(1 + S0 ** 2) / (2 * (1 + S0 ** 2)) + PI_IV / (2 * S0)).b
    best = mp.mpf(0)
    arg = 0.0

    def ub(ab):
        return theta_ub(ab[0], ab[1])

    def probe(ab):
        """Evaluate at the midpoint; returns a certified lower bound."""
        nonlocal best, arg
        m = 0.5 * (ab[0] + ab[1])
        c = mp.make_mpf(theta_iv(iv.mpf(m))._mpi_[0])   # exact, see theta_ub
        if c > best:
            best, arg = c, m

    boxes = [(s0 * i / 32.0, s0 * (i + 1) / 32.0) for i in range(32)]
    val = {}
    for ab in boxes:
        val[ab] = ub(ab)
        probe(ab)
    for _rd in range(rounds):
        boxes = [ab for ab in boxes if val[ab] > best]
        if not boxes:
            break
        top = max(val[ab] for ab in boxes)
        if top - best <= tol or len(boxes) >= nb:
            break
        new = []
        for (a, b) in boxes:
            m = 0.5 * (a + b)
            if not (a < m < b):                 # endpoint resolution reached
                new.append((a, b))
                continue
            for nab in ((a, m), (m, b)):
                val[nab] = ub(nab)
                probe(nab)
                new.append(nab)
        if len(new) == len(boxes):
            break
        boxes = new
    hi = best
    for ab in boxes:
        if val[ab] > hi:
            hi = val[ab]
    assert tail < best, ("Theta* tail bound binds -- raise THETA_S0",
                         float(tail), float(best))
    return iv.mpf([best, hi]), arg



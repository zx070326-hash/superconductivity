def _abs_range(rng):
    """(inf, sup) of |x| over the interval rng.

    TYPE, and it matters (see (R11)): `rng.a` / `rng.b` are DEGENERATE
    `ivmpf`, so both returned values are degenerate `ivmpf`, NOT `mp.mpf`.
    That is deliberate -- every caller here multiplies the result into
    further interval arithmetic (`_sigma_tail`, `_cell_view`,
    `_fam_tail_hk`), and an `mp.mpf` would silently switch those products
    to round-to-NEAREST.  Callers that need a totally ordered scalar (the
    two branch-and-bounds) take `._mpi_[0/1]` explicitly."""
    p, q = rng.a, rng.b
    lo = iv.mpf(0) if (p <= 0 <= q) else min(abs(p), abs(q))
    return lo, max(abs(p), abs(q))


def _definite(rng):
    return not (rng.a <= 0 <= rng.b)


def _hull(x, y):
    return iv.mpf([min(x.a, y.a), max(x.b, y.b)])


ISECT_HIT = [0]       # times _isect found two enclosures DISJOINT


def _isect(x, y):
    """Intersection of two enclosures of the SAME real set (never empty).

    Disjointness is counted, not shrugged off.  Two correctly outward-rounded
    enclosures of one real set ALWAYS overlap -- they both contain the set --
    so `lo > hi` is not a rounding artefact, it means one of the two is wrong.
    The narrower one is still returned so a run can finish, but ISECT_HIT is
    asserted zero by `check_cap_and_isect`, mirroring CAP_HIT."""
    lo = max(x.a, y.a)
    hi = min(x.b, y.b)
    if lo > hi:                      # soundness alarm, not a rounding effect
        ISECT_HIT[0] += 1
        # width comparison in exact mp.mpf.  `x.b - x.a` subtracts two
        # DEGENERATE intervals but is still outward-rounded, so it can come
        # back an ulp wide, and `wide <= wide` returns None (falsy).  Either
        # branch would be sound here -- both x and y enclose the set -- but
        # the (R11) rule is to restore a total order, not to rely on the
        # else branch being harmless.
        wx = mp.make_mpf(x._mpi_[1]) - mp.make_mpf(x._mpi_[0])
        wy = mp.make_mpf(y._mpi_[1]) - mp.make_mpf(y._mpi_[0])
        return x if wx <= wy else y
    return iv.mpf([lo, hi])


def _split_pt(a, b):
    """Bisection point: geometric when the cell spans more than a factor 4."""
    m = float(np.sqrt(a) * np.sqrt(b)) if (a > 0.0 and b > 4.0 * a) \
        else 0.5 * (a + b)
    if not (a < m < b):
        m = 0.5 * (a + b)
    return m if a < m < b else None


def _base_sigma_edges(s_lo, s_hi):
    """Base sigma grid.  Starts AT 0 (the reduced integrand is regular there,
    so there is NO head omission) and is pre-refined around the resonance
    sigma ~ s, where d_sigma^2 etahat changes sign.  The adaptive loop in
    prof_iv does the rest; correctness never depends on this grid."""
    B = max(48.0, 12.0 * s_hi)
    pts = [0.0]
    pts += list(np.geomspace(1e-5, 1.0, 16))
    pts += list(np.geomspace(1.0, 8.0, 10))
    if s_hi > 1e-4:
        bases = [s_lo, s_hi] if s_hi > 1.02 * max(s_lo, 1e-300) else [s_hi]
        for q in (0.2, 0.4, 0.6, 0.8, 0.9, 1.0, 1.1, 1.25, 1.6, 2.2, 3.2):
            for base in bases:
                v = q * base
                if 1e-6 < v < B:
                    pts.append(v)
        for dd in (0.5, 1.0, 2.0, 4.0):
            for base in bases:
                for v in (base - dd, base + dd):
                    if 1e-6 < v < B:
                        pts.append(v)
    pts += list(np.geomspace(8.0, B, 14))
    e = np.unique(np.array(sorted(float(x) for x in pts), dtype=float))
    e = e[e <= B]
    return [float(x) for x in e], B


def _sigma_tail(nm, w, S, B):
    """Rigorous enclosure of the sigma-tail contributions

        int_B^inf |etahat_sigmasigma| dsigma          (value)
        int_B^inf |d_s etahat_sigmasigma| dsigma      (derivative bound)

    via  |X| <= M_X / sigma^5  with  M_X = sup_{sigma>=B} |sigma^5 X|
    evaluated on the COMPACTIFIED chart t = 1/sigma in [0, 1/B]:

        sigma^5 etahat_ss = t^(m-3)[ m(m+1) F + 2(1+m) t F_t + t^2 F_tt ],

    F rational and regular at t = 0.  No decay assumption is made."""
    m = MEXP(nm, w)
    assert m >= 3, (nm, w, m)
    # The chart must cover t in [0, 1/B] where 1/B is the EXACT reciprocal.
    # `1.0 / B` rounds to nearest, and for the default B = 48 it rounds DOWN
    # (fl(1/48) - 1/48 = -1.16e-18), so the sup would have been taken over
    # sigma >= 1/fl(1/B) > B, leaving the sliver (B, 1/fl(1/B)) covered by
    # neither the cells (which end exactly at B) nor the tail.  Taking the
    # upper endpoint of the interval quotient rounds outward instead.
    T = iv.mpf([0, (iv.mpf(1) / iv.mpf(B)).b])
    F = eta_tail_bj(nm, w, S, T)
    f0, f1, f2 = F.c[0], F.c[1], F.c[2]
    g0, g1, g2 = F.c[5], F.c[6], F.c[7]
    br = m * (m + 1) * f0 + 2 * (1 + m) * T * f1 + (T ** 2) * f2
    brs = m * (m + 1) * g0 + 2 * (1 + m) * T * g1 + (T ** 2) * g2
    pw = T ** (m - 3) if m > 3 else _ONE
    M0 = _abs_range(pw * br)[1]
    M1 = _abs_range(pw * brs)[1]
    den = 4 * iv.mpf(B) ** 4
    return iv.mpf([0, M0]) / den, iv.mpf(M1) / den


class ProfInfo(object):
    __slots__ = ('ncell', 'nseg', 'nambig', 'sigmax', 'tail', 'slack',
                 'njet')

    def __init__(self, ncell, nseg, nambig, sigmax, tail, slack, njet):
        self.ncell, self.nseg, self.nambig = ncell, nseg, nambig
        self.sigmax, self.tail, self.slack, self.njet = \
            sigmax, tail, slack, njet


def prof_iv(nm, w, S, rel=1e-9, max_cells=4000, want_der=True,
            verbose=False):
    """Enclosure of  (Uhat(s), d/ds Uhat(s))  valid for EVERY s in S, where

        Uhat(s) := T_f(s)/s^2   (w = 0)   resp.   U_f(s)/s^2   (w = 1)
                 = int_0^inf |d_sigma^2 etahat(sigma,s)| dsigma.

    Method (module docstring, ingredient (2)).  On each sigma-cell [a,b] the
    range of etahat_sigmasigma over the BOX [a,b] x S is enclosed by the
    second-order Taylor form about the cell midpoint m,

        eta''(m) + delta*eta'''(m) + (delta^2/2)*eta''''([a,b] x S),
        delta := [a,b] - m,

    intersected with the direct box evaluation.  If the result excludes 0,
    the sign of eta'' is certified UNIFORMLY in s over the cell; maximal
    runs of equal-sign cells are merged and contribute EXACTLY

        eps * (psi(b_run) - psi(a_run)),      psi := eta_sigma,

    with the run endpoints FIXED grid points -- so the s-derivative of that
    contribution is exactly eps*(psi_s(b_run) - psi_s(a_run)), and no root
    of eta'' is ever located or tracked.  Cells whose enclosure straddles 0
    fall back to  h*[inf|eta''|, sup|eta''|]  (derivative: h*[-M,M] with
    M = sup|d_s eta''|) and are bisected first.  A degenerate (double) root
    can only slow this down; it cannot make it unsound.

    Returns (val_iv, der_iv, ProfInfo)."""
    s_lo, s_hi = float(S.a), float(S.b)
    edges, B = _base_sigma_edges(s_lo, s_hi)
    tailv, tailder = _sigma_tail(nm, w, S, B)
    njet = [1]

    ptc = {}

    def pt(x):
        """jet components at the POINT sigma = x (cached)."""
        r = ptc.get(x)
        if r is None:
            j = eta_bj(nm, w, S, iv.mpf(x))
            njet[0] += 1
            r = j.c
            ptc[x] = r
        return r

    rec = {}

    def touch(a, b):
        k = (a, b)
        r = rec.get(k)
        if r is not None:
            return r
        mc = _split_pt(a, b)
        if mc is None:
            mc = 0.5 * (a + b)
        jm = pt(mc)
        box = eta_bj(nm, w, S, iv.mpf([a, b]))
        njet[0] += 1
        h = iv.mpf(b) - iv.mpf(a)
        dl = iv.mpf([a, b]) - iv.mpf(mc)
        dl2 = (dl ** 2) / 2
        r2 = _isect(jm[2] + dl * jm[3] + dl2 * box.c[4], box.c[2])
        r2s = _isect(jm[7] + dl * jm[8] + dl2 * box.c[9], box.c[7])
        sg = 0
        if _definite(r2):
            sg = 1 if r2.a > 0 else -1
        lo2, hi2 = _abs_range(r2)
        hi2s = _abs_range(r2s)[1]
        fh = float(h.b)
        r = (sg, h, lo2, hi2, hi2s, fh,
             0.0 if sg else fh * float((hi2 - lo2).b), fh * float(hi2))
        rec[k] = r
        return r

    cells = [(edges[i], edges[i + 1]) for i in range(len(edges) - 1)]
    for a, b in cells:
        touch(a, b)

    # --- adaptive refinement.  The stopping rule EQUIDISTRIBUTES the slack:
    # only cells whose own slack exceeds the per-cell share of the target get
    # bisected, so a cell that is already harmless is never touched again.
    # (Float bookkeeping -- it steers the grid only; the assembled enclosure
    # below is pure interval arithmetic and is correct for ANY grid.)
    #
    # STAGNATION RULE (essential when S is a genuine INTERVAL).  For a point
    # s every ambiguous cell eventually becomes sign definite, so the slack
    # goes to zero and `slack <= rel*est` is reachable.  For an interval S
    # the sign of etahat_sigmasigma genuinely differs between the two ends of
    # S on a sigma-set of POSITIVE measure (measured: d log etahat'' /
    # d log s ~ 30 near the resonance, so a 1% wide S already flips the sign
    # over a whole band), and there the slack converges to a positive limit:
    # a pure `rel` test then bisects until max_cells with no gain.  We stop
    # as soon as two consecutive rounds improve the slack by less than 15%.
    slack = 0.0
    prev = float('inf')
    stall = 0
    for _round in range(90):
        est = 0.0
        slack = 0.0
        amb = []
        for i, ab in enumerate(cells):
            r = rec[ab]
            est += r[7]
            if r[0] == 0:
                slack += r[6]
                amb.append((r[6], i))
        est = max(est, 1e-300)
        if slack <= rel * est or not amb or len(cells) >= max_cells:
            break
        stall = stall + 1 if slack > 0.85 * prev else 0
        prev = slack
        if stall >= 2:
            break
        thr = 0.4 * rel * est / max(4, len(amb))
        cut = set(i for sl, i in amb if sl > thr)
        if verbose:
            print(f"    round {_round:3d}: cells={len(cells):5d} "
                  f"amb={len(amb):4d} slack={slack:.3e} est={est:.5g} "
                  f"split={len(cut)}")
        if not cut:
            break
        nc = []
        for i, (a, b) in enumerate(cells):
            m0 = _split_pt(a, b) if i in cut else None
            if m0 is None:
                nc.append((a, b))
            else:
                touch(a, m0)
                touch(m0, b)
                nc.append((a, m0))
                nc.append((m0, b))
        if len(nc) == len(cells):
            break
        cells = nc

    # --- assemble: merge maximal runs of equal-sign cells, telescope -------
    val = iv.mpf(0)
    der = iv.mpf(0)
    nseg = 0
    nambig = 0
    i = 0
    n = len(cells)
    while i < n:
        ab = cells[i]
        sg = rec[ab][0]
        if sg == 0:
            _, h, lo2, hi2, hi2s = rec[ab][:5]
            val = val + h * iv.mpf([lo2, hi2])
            if want_der:
                der = der + h * iv.mpf([-hi2s, hi2s])
            nambig += 1
            i += 1
            continue
        j = i
        while j + 1 < n and rec[cells[j + 1]][0] == sg:
            j += 1
        pa = pt(cells[i][0])
        pb = pt(cells[j][1])
        c = (pb[1] - pa[1]) if sg > 0 else (pa[1] - pb[1])
        lo = c.a if c.a > 0 else mp.mpf(0)      # the exact value is >= 0
        val = val + iv.mpf([lo, c.b])
        if want_der:
            der = der + ((pb[6] - pa[6]) if sg > 0 else (pa[6] - pb[6]))
        nseg += 1
        i = j + 1
    val = val + tailv
    if want_der:
        der = der + iv.mpf([-tailder.b, tailder.b])
    return val, der, ProfInfo(len(cells), nseg, nambig, B,
                              float(tailv.b), slack, njet[0])


# ============================================================================
# SEC. 5.  THE OUTER s-QUADRATURE  ->  THE 12 PAD CV CONSTANTS
# ============================================================================
# M2 builds the twelve pad constants (build_constants()) as
#
#     pv = U_f(s)   (= abs_sig2(nm, s, weightG=True), i.e. the w = 1 profile)
#     W_nm  = I[U_f^2]      = int_0^inf U_f(s)^2 / (2s) ds
#     GU_nm = I[G U_f]      = int_0^inf G(s) U_f(s) / (2s) ds
#     V_W_nm, V_GU_nm       = int_0^inf |d/ds( . )| ds       (const_pair1)
#
# so ALL TWELVE need only the SINGLE weighted profile family U_f (w = 1);
# the unweighted T_f is needed only by the TBAR sups of Sec. 6.
#
# In terms of the reduced profile  Uhat(s) := U_f(s)/s^2  returned by
# prof_iv (regular at s = 0):
#
#     h_W (s) = s^3 Uhat^2 / 2,   h_W'  = (3 s^2 Uhat^2 + 2 s^3 Uhat Uhat')/2
#     h_GU(s) = G(s) s Uhat / 2,  h_GU' = (G' s Uhat + G Uhat + G s Uhat')/2
#
# QUADRATURE.  On a cell [a,b] of width h and midpoint m, with [P,Q] any
# enclosure of h'([a,b]),
#
#     int_a^b h ds  in  h*h(m) + (h^2/8)*[-(Q-P), +(Q-P)] .
#
# (Write h(s) = h(m) + int_m^s h'; the constant part of h' integrates to
# exactly h*h(m) because int_a^b (s-m) ds = 0, and the deviation is bounded
# by (Q-P)/2 * int_a^b |s-m| ds = (Q-P) h^2 / 8.)  It needs only ONE point
# evaluation plus ONE box evaluation per cell, and -- this is the reason it
# was chosen over any higher-order rule -- it assumes NOTHING beyond
# h Lipschitz with h' in [P,Q] almost everywhere.  Uhat is a total variation
# in sigma; it is Lipschitz in s, but it is NOT known to be C^2 (a point
# where two roots of etahat_sigmasigma collide is exactly a point where
# Uhat'' may jump).  Every Newton-Cotes / Gauss / Euler-Maclaurin remainder
# would need a derivative that is not certified to exist, so the rule above
# is the highest order that is honest here.  Sec. 1.J records this.
#
# WHY THE GRID IS ADAPTIVE AND NOT GEOMETRIC.  (Q-P) is produced by a BOX
# profile evaluation prof_iv(nm, 1, [a,b]).  Measured: for an INTERVAL S the
# sign of etahat_sigmasigma really does differ across S on a sigma-band whose
# width is proportional to the relative width of S (dlog etahat''/dlog s is
# of order 30 near the resonance), so those sigma-cells stay ambiguous no
# matter how finely they are split and (Q-P) comes out about 10^2 times the
# true oscillation of h'.  The Peano term is still third order in the cell
# width, just with a large constant, and the required cell width varies by
# four orders of magnitude across the s-axis (h_W drops by 10^7 between
# s = 0.5 and s = 25).  A uniform geometric grid at the width the peak needs
# would be ~10^5 cells; equidistributing the Peano slack instead costs a few
# thousand.  As in Sec. 4, the refinement is float bookkeeping that only
# steers the grid: the assembled enclosure is correct for ANY grid.
#
# V1 = int |h'| uses the same sign-definite total-variation rule as Sec. 4,
# now in the OUTER variable: on a maximal run of cells whose h'-enclosure is
# sign definite, int |h'| = |h(b_run) - h(a_run)| exactly, so only the run
# ENDPOINTS need an extra point evaluation (typically 2-6 of them).  Cells
# whose h'-enclosure straddles 0 fall back to h*[inf|h'|, sup|h'|].
OUTER_TOP = 1.0e6
OUTER_LO = 1.0e-4


def outer_edges(rho=1.06, lo=OUTER_LO, top=OUTER_TOP):
    """Outer s-grid.  Starts AT s = 0 (no head omission: Uhat is regular
    there because the exact double zero of R_f at s = 0 was divided out)."""
    e = [0.0, lo]
    x = lo
    while x < top * (1.0 - 1e-12):
        x = min(x * rho, top)
        e.append(x)
    return e


def _h_pair(kind, S, uv, ud):
    """(h, h') of the outer integrand from Uhat = uv and d_s Uhat = ud."""
    if kind == 'W':
        S2 = S ** 2
        u2 = uv ** 2
        return (S2 * S * u2) / 2, (3 * S2 * u2 + 2 * S2 * S * uv * ud) / 2
    dd = 1 + S ** 2
    g = 1 / dd
    gp = -2 * S / (dd ** 2)
    return (g * S * uv) / 2, (gp * S * uv + g * uv + g * S * ud) / 2


# ---- picklable worker so the heavy part can run in a process pool ---------
def _pack(x):
    return x._mpi_


def _unpack(t):
    return iv.make_mpf(t)


def _job(arg):
    """arg = ('P', nm, w, x, rel, maxc) -> profile at the POINT x
           = ('B', nm, w, a, b, rel, maxc) -> profile over the BOX [a,b]"""
    if arg[0] == 'P':
        _, nm, w, x, rel, maxc = arg
        S = iv.mpf(x)
    else:
        _, nm, w, a, b, rel, maxc = arg
        S = iv.mpf([a, b])
    v, d, info = prof_iv(nm, w, S, rel=rel, max_cells=maxc)
    return _pack(v), _pack(d), info.ncell, info.nseg, info.nambig, info.njet


_POOL = [None]
NJET = [0]
NCELL = [0]


def _pmap(jobs):
    p = _POOL[0]
    out = list(p.imap(_job, jobs, chunksize=1)) if p is not None \
        else [_job(j) for j in jobs]
    for r in out:
        NCELL[0] += r[2]
        NJET[0] += r[5]
    return [(_unpack(r[0]), _unpack(r[1])) for r in out]



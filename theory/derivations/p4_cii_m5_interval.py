# ============================================================================
# SEC. 1.  EXACT INTEGER COEFFICIENT TABLE FOR  Nhat_f(sigma, s)
# ============================================================================
# R_f(s,sigma) / sigma^2 = s^2 * Nhat_f(sigma,s) / (a^p A^p B^p g^p),
# i.e.   eta = G^w R_f/(2 sigma)
#            = s^2 * sigma * Nhat_f / (2 a^p A^p B^p g^(p+w)).
# Nhat is even in sigma AND even in s, so it is stored as a table in the
# variables  X = sigma^2,  Z = s^2:   Nhat = sum_{i,j} NTAB[nm][i][j] X^i Z^j.
# Generated by _scratch_ir/m5_emit.py (sympy, exact) and verified there
# against the symbolic definition of R_f; re-verified numerically in Sec. 8
# against M2's own Rk/h_sig2.
NTAB = {
    # f = G  (p=1):  Nhat = (10 + 2 Z) + 2 X
    'G': [[10, 2],
          [2]],
    # f = kappa (p=2)
    'kap': [[-20, -36, -12, 4],
            [-36, -24, -2, 20, 2],
            [-12, -2, -40, -2],
            [4, 20, -2],
            [0, 2]],
    # f = phi0 (p=3)
    'phi': [[-32, -116, -150, -82, -28, -24, -14, -2],
            [-116, -308, -240, 80, 244, 132, 16],
            [-150, -240, -336, -218, -84, 18, 2],
            [-82, 80, -218, -68, -32, 8],
            [-28, 244, -84, -32, -20],
            [-24, 132, 18, 8],
            [-14, 16, 2],
            [-2]],
}
PPOW = {'G': 1, 'kap': 2, 'phi': 3}
# K = deg_sigma(Nhat) = 2*(len(NTAB)-1)
KDEG = {nm: 2 * (len(NTAB[nm]) - 1) for nm in NTAB}
# m = 6p + 2w - K - 1  (order of vanishing of eta(1/t) at t = 0)
def MEXP(nm, w):
    return 6 * PPOW[nm] + 2 * w - KDEG[nm] - 1



# ============================================================================
# SEC. 2.  BJ -- interval bivariate jet, d_x^i d_s^j for i <= 4, j <= 1
# ============================================================================
# Component order: (u0..u4, v0..v4) with  u_i = d_x^i f,  v_i = d_x^i d_s f;
# x = the "fast" variable (sigma in eta_bj, t = 1/sigma in eta_tail_bj),
# s = the outer variable.
#
# WHY FOURTH ORDER.  A naive interval evaluation of d_x^2 f on a cell of
# width h overestimates the true range by O(h) with a LARGE constant
# (measured: the enclosure width is ~230*h for f = phi0 at sigma ~ 1, while
# the true range width is ~5*h).  Sign-definiteness of d_sigma^2 eta is the
# whole engine of Sec. 4, so that overestimate would force h ~ 1e-2 and
# ~2e3 cells per profile.  Instead Sec. 4 encloses d_x^2 f by the SECOND
# ORDER TAYLOR FORM about the cell midpoint m,
#
#     f''(m+delta) = f''(m) + delta f'''(m) + (delta^2/2) f''''(xi),
#
# where f''(m), f'''(m) are POINT evaluations (no dependency blow-up at all)
# and only f'''' -- multiplied by delta^2/2 = O(h^2/8) -- is taken from the
# naive box evaluation.  The radius is then O(h^2) and ~30x fewer cells are
# needed.  That is what the 4th x-order is for; the 5-component s-block
# gives the same treatment to d_s d_x^2 f, which is what the s-derivative of
# the profile needs.
#
# `kind` enables cheap specialised products:
#   'x' : depends on x only  (all v_i = 0)
#   's' : depends on s only  (u1..u4 = v1..v4 = 0)
#   'f' : full
_IVT = type(iv.mpf(0))
_ZERO = iv.mpf(0)
_ONE = iv.mpf(1)
_Z5 = (_ZERO,) * 5


class BJ(object):
    __slots__ = ('c', 'kind')

    def __init__(self, c, kind='f'):
        self.c = c
        self.kind = kind

    @staticmethod
    def const(x):
        v = x if isinstance(x, _IVT) else iv.mpf(x)
        return BJ((v,) + _Z5 + (_ZERO,) * 4, 'x')

    @staticmethod
    def xonly(u0, u1=_ZERO, u2=_ZERO, u3=_ZERO, u4=_ZERO):
        return BJ((u0, u1, u2, u3, u4) + _Z5, 'x')

    @staticmethod
    def sonly(v, dv):
        return BJ((v, _ZERO, _ZERO, _ZERO, _ZERO,
                   dv, _ZERO, _ZERO, _ZERO, _ZERO), 's')

    def __add__(self, o):
        if not isinstance(o, BJ):
            o = BJ.const(o)
        k = self.kind if self.kind == o.kind else 'f'
        return BJ(tuple(a + b for a, b in zip(self.c, o.c)), k)
    __radd__ = __add__

    def __neg__(self):
        return BJ(tuple(-a for a in self.c), self.kind)

    def __sub__(self, o):
        if not isinstance(o, BJ):
            o = BJ.const(o)
        return self + (-o)

    def __rsub__(self, o):
        return (-self) + o

    def __mul__(self, o):
        if not isinstance(o, BJ):
            return BJ(tuple(a * o for a in self.c), self.kind)
        u0, u1, u2, u3, u4, v0, v1, v2, v3, v4 = self.c
        w0, w1, w2, w3, w4, x0, x1, x2, x3, x4 = o.c
        if o.kind == 's':               # w1..w4 = x1..x4 = 0
            return BJ((u0 * w0, u1 * w0, u2 * w0, u3 * w0, u4 * w0,
                       v0 * w0 + u0 * x0, v1 * w0 + u1 * x0,
                       v2 * w0 + u2 * x0, v3 * w0 + u3 * x0,
                       v4 * w0 + u4 * x0),
                      's' if self.kind == 's' else 'f')
        if o.kind == 'x':               # x0..x4 = 0
            return BJ((u0 * w0,
                       u1 * w0 + u0 * w1,
                       u2 * w0 + 2 * u1 * w1 + u0 * w2,
                       u3 * w0 + 3 * (u2 * w1 + u1 * w2) + u0 * w3,
                       u4 * w0 + 4 * (u3 * w1 + u1 * w3) + 6 * u2 * w2
                       + u0 * w4,
                       v0 * w0,
                       v1 * w0 + v0 * w1,
                       v2 * w0 + 2 * v1 * w1 + v0 * w2,
                       v3 * w0 + 3 * (v2 * w1 + v1 * w2) + v0 * w3,
                       v4 * w0 + 4 * (v3 * w1 + v1 * w3) + 6 * v2 * w2
                       + v0 * w4),
                      'x' if self.kind == 'x' else 'f')
        if self.kind in ('s', 'x'):
            return o * self
        return BJ((
            u0 * w0,
            u1 * w0 + u0 * w1,
            u2 * w0 + 2 * u1 * w1 + u0 * w2,
            u3 * w0 + 3 * (u2 * w1 + u1 * w2) + u0 * w3,
            u4 * w0 + 4 * (u3 * w1 + u1 * w3) + 6 * u2 * w2 + u0 * w4,
            v0 * w0 + u0 * x0,
            v1 * w0 + u1 * x0 + v0 * w1 + u0 * x1,
            v2 * w0 + u2 * x0 + 2 * (v1 * w1 + u1 * x1) + v0 * w2 + u0 * x2,
            v3 * w0 + u3 * x0 + 3 * (v2 * w1 + u2 * x1)
            + 3 * (v1 * w2 + u1 * x2) + v0 * w3 + u0 * x3,
            v4 * w0 + u4 * x0 + 4 * (v3 * w1 + u3 * x1)
            + 6 * (v2 * w2 + u2 * x2) + 4 * (v1 * w3 + u1 * x3)
            + v0 * w4 + u0 * x4,
        ), 'f')
    __rmul__ = __mul__

    def sqr(self):
        """self*self, never forming `z*z` for a sign-crossing interval z
        (see M3 Sec.1: mpmath.iv's naive product of an interval with itself
        can produce a spurious negative lower bound; `**2` is correct)."""
        u0, u1, u2, u3, u4, v0, v1, v2, v3, v4 = self.c
        return BJ((
            u0 ** 2,
            2 * u0 * u1,
            2 * u1 ** 2 + 2 * u0 * u2,
            2 * u0 * u3 + 6 * u1 * u2,
            2 * u0 * u4 + 8 * u1 * u3 + 6 * u2 ** 2,
            2 * u0 * v0,
            2 * (u1 * v0 + u0 * v1),
            2 * (u2 * v0 + 2 * u1 * v1 + u0 * v2),
            2 * (u3 * v0 + 3 * (u2 * v1 + u1 * v2) + u0 * v3),
            2 * (u4 * v0 + 4 * (u3 * v1 + u1 * v3) + 6 * u2 * v2 + u0 * v4),
        ), self.kind)

    def __truediv__(self, o):
        if not isinstance(o, BJ):
            return BJ(tuple(a / o for a in self.c), self.kind)
        u0, u1, u2, u3, u4, v0, v1, v2, v3, v4 = self.c
        w0, w1, w2, w3, w4, x0, x1, x2, x3, x4 = o.c
        r0 = u0 / w0
        r1 = (u1 - r0 * w1) / w0
        r2 = (u2 - 2 * r1 * w1 - r0 * w2) / w0
        r3 = (u3 - 3 * (r2 * w1 + r1 * w2) - r0 * w3) / w0
        r4 = (u4 - 4 * (r3 * w1 + r1 * w3) - 6 * r2 * w2 - r0 * w4) / w0
        s0 = (v0 - r0 * x0) / w0
        s1 = (v1 - r1 * x0 - s0 * w1 - r0 * x1) / w0
        s2 = (v2 - r2 * x0 - 2 * (s1 * w1 + r1 * x1)
              - s0 * w2 - r0 * x2) / w0
        s3 = (v3 - r3 * x0 - 3 * (s2 * w1 + r2 * x1)
              - 3 * (s1 * w2 + r1 * x2) - s0 * w3 - r0 * x3) / w0
        s4 = (v4 - r4 * x0 - 4 * (s3 * w1 + r3 * x1)
              - 6 * (s2 * w2 + r2 * x2) - 4 * (s1 * w3 + r1 * x3)
              - s0 * w4 - r0 * x4) / w0
        return BJ((r0, r1, r2, r3, r4, s0, s1, s2, s3, s4), 'f')

    def __pow__(self, n):
        assert isinstance(n, int) and n >= 1
        if n == 1:
            return self
        if n == 2:
            return self.sqr()
        r = self.sqr()
        for _ in range(n - 2):
            r = r * self
        return r

    def __repr__(self):
        return "BJ" + repr(self.c)


def _poly_pair(coeffs, z, dz):
    """Horner for  P(z)  and  dP/ds = P'(z)*dz  with z = s^2, dz = 2s."""
    v = iv.mpf(coeffs[-1])
    d = _ZERO
    for k in range(len(coeffs) - 2, -1, -1):
        d = d * z + v
        v = v * z + iv.mpf(coeffs[k])
    return v, d * dz


# ============================================================================
# SEC. 3.  etahat(sigma, s) AND ITS sigma-TAIL CHART, AS BJs
# ============================================================================
def eta_bj(nm, w, S, SG):
    """BJ (in x = sigma, s) of  eta = G(sigma)^w R_f(s,sigma)/(2 sigma)
    DIVIDED BY s^2 -- i.e. of the reduced integrand

        etahat(sigma,s) := eta(sigma,s) / s^2
                         = sigma * Nhat(sigma,s) / (2 a^p A^p B^p g^(p+w)).

    Dividing out the exact double zero of R_f at s = 0 keeps the whole outer
    s-integrand regular at s = 0 (Sec. 5), so there is no head omission.
    S, SG are iv.mpf points or intervals."""
    p = PPOW[nm]
    tab = NTAB[nm]
    Z = S ** 2
    dZ = 2 * S
    X = SG ** 2
    two = iv.mpf(2)
    jX = BJ.xonly(X, 2 * SG, two)
    # Nhat = sum_i C_i(Z) X^i, Horner in X
    cv, cd = _poly_pair(tab[-1], Z, dZ)
    N = BJ.sonly(cv, cd)
    for i in range(len(tab) - 2, -1, -1):
        cv, cd = _poly_pair(tab[i], Z, dZ)
        N = N * jX + BJ.sonly(cv, cd)
    d = S - SG
    e = S + SG
    A = BJ((1 + d ** 2, -2 * d, two, _ZERO, _ZERO,
            2 * d, -two, _ZERO, _ZERO, _ZERO), 'f')
    B = BJ((1 + e ** 2, 2 * e, two, _ZERO, _ZERO,
            2 * e, two, _ZERO, _ZERO, _ZERO), 'f')
    a = BJ.sonly(1 + Z, dZ)
    g = BJ.xonly(1 + X, 2 * SG, two)
    jsg = BJ.xonly(SG, _ONE)
    den = (a ** p) * ((A ** p) * (B ** p)) * (g ** (p + w)) * two
    return (jsg * N) / den


def eta_tail_bj(nm, w, S, T):
    """BJ (in x = t = 1/sigma, s) of  F(t,s), where

        etahat(1/t, s) = t^m F(t,s),   m = 6p + 2w - K - 1,
        F = Ntil / ( 2 a^p Atil^p Btil^p (1+t^2)^(p+w) ),
        Ntil(t,s) = sum_i C_i(s^2) t^(K-2i),
        Atil = t^2 + (s t - 1)^2,   Btil = t^2 + (s t + 1)^2.

    Regular at t = 0 (Atil, Btil -> 1), so the sigma-tail is a genuine
    enclosure, not a decay assumption."""
    p = PPOW[nm]
    tab = NTAB[nm]
    Z = S ** 2
    dZ = 2 * S
    X = T ** 2
    two = iv.mpf(2)
    jX = BJ.xonly(X, 2 * T, two)
    # Ntil = sum_i C_i(Z) t^(K-2i):  Horner in X from i = 0 upward
    cv, cd = _poly_pair(tab[0], Z, dZ)
    N = BJ.sonly(cv, cd)
    for i in range(1, len(tab)):
        cv, cd = _poly_pair(tab[i], Z, dZ)
        N = N * jX + BJ.sonly(cv, cd)
    ST = S * T
    u = ST - 1
    v = ST + 1
    # Atil = t^2 + (s t - 1)^2 ;  d/dt = 2t + 2 s u ;  d^2/dt^2 = 2 + 2 s^2
    fourS = 4 * S
    A = BJ((X + u ** 2, 2 * T + 2 * S * u, 2 + 2 * Z, _ZERO, _ZERO,
            2 * T * u, 2 * (u + ST), fourS, _ZERO, _ZERO), 'f')
    B = BJ((X + v ** 2, 2 * T + 2 * S * v, 2 + 2 * Z, _ZERO, _ZERO,
            2 * T * v, 2 * (v + ST), fourS, _ZERO, _ZERO), 'f')
    a = BJ.sonly(1 + Z, dZ)
    g = BJ.xonly(1 + X, 2 * T, two)
    den = (a ** p) * ((A ** p) * (B ** p)) * (g ** (p + w)) * two
    return N / den



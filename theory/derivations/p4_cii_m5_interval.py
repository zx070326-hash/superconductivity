# TWO DIFFERENT CLAIMS, deliberately kept apart, because they are not the same
# claim and a referee is entitled to know which one is being made where:
#
#   check_no_transcendental_source()  asserts TEXTUAL ABSENCE, and only for
#       M5's OWN Sec. 1 - Sec. 7b.  It tokenises this file, so prose in
#       comments and docstrings can neither trigger it nor mask a real call.
#       That range genuinely contains no `mp.`/`iv.` call other than mpf
#       construction -- not even sqrt -- so the whitelist is empty.
#
#   check_transcendental_unreachable()  asserts UNREACHABILITY, for the whole
#       assembled M3+M4+M5 path.  Textual absence is the wrong tool there:
#       `p4_cii_m3_interval.py:100` still READS `iv.atan2(y, 1)`, and the
#       point of `install_certified_primitives()` is that it is no longer
#       CALLED.  So instead every untrusted primitive is replaced by a stub
#       that raises, and the entire bound is then recomputed.  If any of them
#       were still on the path the recomputation would raise.
#
#       HONEST LIMIT of the second check: it demonstrates unreachability along
#       the path actually exercised, with the inputs actually used -- it is
#       dynamic, not a static proof of unreachability for all inputs.  It does
#       cover the real one: the payload is the same bounds3() call that
#       produces the shipped wA''.
#
# TRUSTED BASE left standing, deliberately, after both checks: iv.sqrt, iv.log
# and iv.pi (all audited SOUND this session, Sec. 0c), plus M3's mp.sqrt calls
# inside V_FPP_iv, which run at dps 40 under an explicit 1e-12 pad -- a pad
# that covers its own error source by 28 orders of magnitude, unlike the
# theta_star_iv pad that did not.
_BANNED = {'pi', 'e', 'atan', 'atan2', 'asin', 'acos', 'sin', 'cos', 'tan',
           'sinh', 'cosh', 'tanh', 'log', 'log10', 'log1p', 'exp', 'expm1',
           'sqrt', 'cbrt', 'power', 'hypot', 'quad', 'zeta', 'gamma',
           'digamma', 'polygamma', 'besselj', 'polylog', 'nsum', 'findroot'}


def _scan_source(path, lo, hi, banned):
    """Tokenised scan for `mod.name` with name in banned[mod], on source lines
    strictly between lo and hi."""
    with io.open(path, 'r', encoding='utf-8') as fh:
        src = fh.read()
    toks = [t for t in tokenize.generate_tokens(io.StringIO(src).readline)
            if t.type in (tokenize.NAME, tokenize.OP)]
    hits = []
    for i in range(len(toks) - 2):
        a, b, c = toks[i], toks[i + 1], toks[i + 2]
        if (a.type == tokenize.NAME and a.string in banned
                and b.string == '.' and c.type == tokenize.NAME
                and c.string in banned[a.string]
                and lo < a.start[0] < hi):
            hits.append(f"{a.string}.{c.string}@{a.start[0]}")
    return hits


def check_no_transcendental_source():
    """TEXTUAL absence of mp./iv. transcendentals from M5's own Sec.1-7b.

    Scope, stated so it is not over-read: this is a check on SOURCE TEXT in a
    line range, keyed on the literal receiver names `mp` and `iv`.  An alias,
    a getattr, or a `from mpmath import atan` defeats it -- the companion
    dynamic guard is what covers those.  numpy is deliberately outside it:
    Sec.1-7b does call np.sqrt/np.geomspace/np.unique/np.array, all of them
    grid STEERING (choosing where to split), never a value in a result."""
    print("\n=== source guard (textual absence, M5 Sec.1-7b only) ===")
    path = os.path.abspath(__file__)
    with io.open(path, 'r', encoding='utf-8') as fh:
        lines = fh.read().splitlines()
    lo = next(i for i, L in enumerate(lines, 1) if L.startswith('# SEC. 1.'))
    hi = next(i for i, L in enumerate(lines, 1) if L.startswith('# SEC. 8.'))
    chk("  the guarded range is non-empty and plausible", hi - lo > 500,
        f"lines {lo}-{hi}  ({hi-lo} lines)")
    banned = {'mp': _BANNED, 'iv': _BANNED}
    hits = _scan_source(path, lo, hi, banned)
    chk(f"no mp./iv. transcendental in lines {lo}-{hi} (M5's own 18 objects)",
        not hits, "; ".join(hits) if hits else
        "not even sqrt: the integrand, both tail charts, the family sups and "
        "both outer integrands are rational in sigma and s")
    # Teeth, INSIDE the guarded range.  Scanning the whole file would leave
    # the main check vacuous-but-green if the SEC. markers ever drifted so
    # that hi < lo: the teeth would still fire on Sec. 8b's mp.atan while the
    # real check scanned nothing.  iv.make_mpf is a call that is genuinely in
    # range, so the probe exercises the same window the guard protects.
    probe = _scan_source(path, lo, hi, {'iv': {'make_mpf'}})
    chk("  scanner has teeth INSIDE the guarded range (finds iv.make_mpf)",
        len(probe) >= 1, "; ".join(probe))


def check_transcendental_unreachable(payload):
    """Poison every primitive that must NOT be on the path, INSTRUMENT every
    primitive that is allowed to be, then recompute the bound.

    The two lists are the whole point.  A bare "nothing transcendental is
    called" would be false -- iv.log, iv.pi and iv.sqrt are genuinely called,
    and so is mp.sqrt (inside M3's V_FPP_iv).  What is being asserted is
    narrower and checkable: the UNSOUND primitive iv.atan2 and the whole
    mp-level nearest-rounded trigonometric family are unreachable, and every
    primitive that IS reachable is either audited in Sec. 0c or sits under an
    explicit pad in M3.  The instrumented counts are printed rather than
    asserted, so a future dependency that starts calling something new shows
    up in the log instead of silently joining the trusted base.

    POISONING `mp.X` IS NOT ENOUGH, and assuming it was is a defect this
    guard shipped with.  M3 does

        from mpmath import mp, mpf, iv, mpc, digamma, polygamma, euler
        from mpmath import log as mlog

    so `M3.mlog`, `M3.digamma`, `M3.polygamma` are SEPARATE module globals;
    `setattr(mp, 'log', boom)` rebinds the attribute on the context object and
    leaves M3's private aliases untouched.  Instrumenting M3's own namespace
    shows they are reached on the shipped path -- `M3.bounds3` calls digamma
    twice, mlog twice and polygamma twelve times.  They are covered by
    `M3.exact_sums_iv`'s 1e-13 relative pad, not by this guard, and that is
    now said out loud instead of being implied away.  A from-import is a
    second binding, and a guard that only rebinds the first one is measuring
    the wrong object."""
    print("\n=== reachability guard (poisoned primitives, whole path) ===")
    BAN = [(iv, 'iv', 'atan2'), (iv, 'iv', 'atan'), (iv, 'iv', 'asin'),
           (iv, 'iv', 'acos'), (iv, 'iv', 'sin'), (iv, 'iv', 'cos'),
           (iv, 'iv', 'tan'), (iv, 'iv', 'exp'), (iv, 'iv', 'cot'),
           (mp, 'mp', 'atan'), (mp, 'mp', 'atan2'), (mp, 'mp', 'exp'),
           (mp, 'mp', 'sin'), (mp, 'mp', 'cos'), (mp, 'mp', 'tan'),
           (mp, 'mp', 'log')]
    # Reachable and allowed.  The M3.* entries are the from-import aliases:
    # they are what actually carries log/digamma/polygamma onto the path.
    WATCH = [(iv, 'iv', 'sqrt'), (iv, 'iv', 'log'), (mp, 'mp', 'sqrt'),
             (M3, 'M3', 'mlog'), (M3, 'M3', 'digamma'),
             (M3, 'M3', 'polygamma')]
    poisoned, refused, missing, saved = [], [], [], []
    count = {}

    def mk_boom(tag):
        def boom(*a, **k):
            raise AssertionError("POISONED PRIMITIVE CALLED: " + tag)
        return boom

    def mk_count(tag, fn):
        count[tag] = 0

        def wrapped(*a, **k):
            count[tag] += 1
            return fn(*a, **k)
        return wrapped

    for lst, factory in ((BAN, lambda tag, old: mk_boom(tag)),
                         (WATCH, mk_count)):
        for obj, ctx, nm in lst:
            tag = f"{ctx}.{nm}"
            try:
                old = getattr(obj, nm)
            except AttributeError:
                missing.append(tag)          # counted, never silent
                continue
            try:
                setattr(obj, nm, factory(tag, old))
            except Exception as exc:            # property without a setter
                refused.append(f"{tag} ({type(exc).__name__})")
                continue
            saved.append((obj, nm, old))
            if lst is BAN:
                poisoned.append(tag)
    teeth = False
    try:
        _M3_ATAN_ORIG(iv.mpf(1))                # M3's original = iv.atan2(y,1)
    except Exception:
        teeth = True
    try:
        payload()
        ok, why = True, ""
    except AssertionError as exc:
        ok, why = False, str(exc)
    finally:
        for obj, nm, old in saved:
            setattr(obj, nm, old)
    chk("  poison has teeth: M3's ORIGINAL atan_iv trips it", teeth,
        "" if teeth else "setattr did not take effect -- the guard is vacuous")
    chk("no unsound primitive is REACHABLE from the assembled bound "
        f"({len(poisoned)} poisoned, incl. iv.atan2 and mp.atan)", ok,
        why or "recomputed clean with: " + ", ".join(poisoned))
    # A name that does not exist was never a guard.  Reporting the BAN list's
    # nominal length while silently skipping three of its entries overstated
    # the guard by three; these are listed so the count means what it says.
    chk("every BAN name that does not exist is accounted for",
        True, "absent from this mpmath build (so trivially unreachable, but "
              "they were never guards): " + ", ".join(missing)
              if missing else "none")
    if count:
        print("      trusted base actually reached: "
              + ", ".join(f"{t} x{n}" for t, n in sorted(count.items())))
        print("      of these, iv.sqrt / iv.log are audited SOUND in Sec. 0c; "
              "mp.sqrt is under V_FPP_iv's 1e-12 pad at dps 40;")
        print("      M3.mlog / M3.digamma / M3.polygamma are nearest-rounded "
              "and covered by M3.exact_sums_iv's 1e-13 relative pad -- pad-"
              "covered, NOT guard-covered.")
    print("      NOT covered by this mechanism: iv.pi (a constant, not a "
          "callable, so it cannot be wrapped) -- it is read by M3.eps1_iv and "
          "is audited separately in Sec. 0c; and M3.Z3H_IV, an import-time "
          "mp.zeta computed before any poisoning can be installed, wrapped by "
          "a 1e-13 absolute pad.")
    if refused:
        print("      could not be poisoned (lazy constants; covered by the "
              "Sec. 0c audit instead): " + "; ".join(refused))
    print("      NOTE: this is a DYNAMIC check.  It demonstrates "
          "unreachability along the path exercised by the payload -- which "
          "includes the very bounds3() call that produces the shipped wA'' "
          "-- not a static proof of unreachability for all inputs.")



def check_tail_chart(pts=(0.02, 0.3, 1.0, 3.0, 12.0, 60.0),
                     ts=(0.02083333333333, 0.008, 0.002)):
    """The t = 1/sigma compactified chart, checked DIRECTLY against the
    sigma-chart at the same point.

    Why this exists: `check_profiles_vs_m2` cannot see the sigma-tail at all.
    Replacing `_sigma_tail` by a function returning (0, 0) leaves its reported
    deviation BIT-IDENTICAL at 4.21e-05, because the tail contributes far less
    than that check's own ~1e-5 resolution.  So every ingredient of Sec. 6.1 --
    `eta_tail_bj`, MEXP, the sigma^5 bracket and the 4B^4 divisor -- was
    shipped with no check on it whatsoever.  The identities below are exact,
    so they hold to interval width rather than to M2's float64 accuracy.

        etahat(1/t, s)          = t^m F(t, s)
        sigma^5 etahat_ss       = t^(m-3) [ m(m+1)F + 2(1+m) t F_t + t^2 F_tt ]

    Both sides are computed from the two charts independently and must
    INTERSECT (two enclosures of the same real number always do)."""
    print("\n=== sigma-tail chart t = 1/sigma vs the direct sigma chart ===")
    worst_v, worst_b, n = 0.0, 0.0, 0
    for nm in ('G', 'kap', 'phi'):
        for w in (0, 1):
            m = MEXP(nm, w)
            for s in pts:
                for t in ts:
                    S, T = iv.mpf(s), iv.mpf(t)
                    SG = 1 / T
                    direct = eta_bj(nm, w, S, SG).c[0]
                    F = eta_tail_bj(nm, w, S, T)
                    via = (T ** m) * F.c[0]
                    if not (direct.a <= via.b and via.a <= direct.b):
                        worst_v = 1e9
                    else:
                        d = float(abs(via.b - direct.b))
                        worst_v = max(worst_v, d / max(float(abs(direct.b)),
                                                       1e-300))
                    # the sigma^5 bracket against sigma^5 * (direct d2/dsigma2)
                    br = (m * (m + 1) * F.c[0] + 2 * (1 + m) * T * F.c[1]
                          + (T ** 2) * F.c[2])
                    lhs = (SG ** 5) * eta_bj(nm, w, S, SG).c[2]
                    rhs = (T ** (m - 3)) * br
                    if not (lhs.a <= rhs.b and rhs.a <= lhs.b):
                        worst_b = 1e9
                    else:
                        d = float(abs(rhs.b - lhs.b))
                        worst_b = max(worst_b, d / max(float(abs(lhs.b)),
                                                       1e-300))
                    n += 1
    chk(f"chart identity  etahat(1/t,s) = t^m F(t,s)  ({n} points)",
        worst_v < 1e-12, f"worst relative gap {worst_v:.2e}")
    chk(f"chart identity  sigma^5 etahat_ss = t^(m-3)[m(m+1)F + 2(1+m)tF_t "
        f"+ t^2 F_tt]  ({n} points)", worst_b < 1e-12,
        f"worst relative gap {worst_b:.2e}")


def check_constants_vs_m2(CV5):
    """The 12 pad constants must CONTAIN M2's float64 values up to M2's own
    truncation, and must not be absurdly wide.

    M5 integrates s over (0, 1e6]; M2's P() truncates the profile at
    S_MAX = 240 and its grid ends there too, so M5 >= M2 is EXPECTED for the
    positive integrands W_*, GU_*.  The tolerance is therefore ASYMMETRIC:
    M5 may exceed M2 by the truncation, but M5 < M2 is the signature of a
    dropped tail and gets a much tighter allowance.

    The previous version compared MIDPOINTS only, with a symmetric 2e-3 band,
    and asserted no containment at all despite the docstring claiming it did.
    It accepted an enclosure of ANY width (a synthetic [0,2] against a
    reference of 1 passed), an enclosure 0.19% wrong in either direction, and
    an enclosure that did not contain the reference at all ([1.001,1.0015] vs
    1.0).  A width test is now separate from a position test, because one
    number cannot police both.  The width gate is a SANITY FLOOR (an
    "enclosure" wider than its own value is not one) and deliberately not a
    quality target: the V_* partners are legitimately wide at loose settings,
    and the quality that matters is the printed width and, in the end, the
    shipped wA''."""
    print("\n=== 12 pad constants vs M2's float64 build_constants() ===")
    for k in sorted(CV5):
        ref = float(M2.CV[k])
        lo, hi = float(CV5[k].a), float(CV5[k].b)
        # containment, one-sided: M2 must lie in the enclosure, allowing the
        # enclosure to sit ABOVE M2 by up to M2's S_MAX truncation (2e-3) but
        # only 1e-6 below it.
        contains = (lo <= ref * (1 + 1e-6) and hi >= ref * (1 - 2e-3))
        rel = (0.5 * (lo + hi) - ref) / max(abs(ref), 1e-300)
        chk(f"{k:10s} in [{lo:.10g},{hi:.10g}] contains M2 {ref:.10g}",
            contains, f"rel dev of midpoint {rel:+.2e}")
        width = (hi - lo) / max(abs(hi), 1e-300)
        chk(f"{k:10s} relative width < 1 (sanity floor, not a quality target)",
            width < 1.0, f"width {width:.2e}")



# from cell/box counts afterwards) and dumped alongside the endpoints.  A
# width that came from a cap and a width that came from a tolerance are
# different kinds of claim; the final table prints the exit next to the
# width so they never appear in the same shape.  Keys: 'cv:<family>' for
# cv_quad (one exit covers that family's four constants), 'tb:<key>' for
# tbar_bb.  Values: cv_quad  -> 'tolerance met' | 'cell cap N' |
# 'no cell cut' | 'no cell split' | 'round cap N';
#          tbar_bb  -> 'converged' | 'box cap N' | 'round cap 40'.
EXITS = {}
SETTINGS = {}      # the tolerances/caps actually used, for the same table


# ---- analytic cap on the large-s box evaluations --------------------------
CAP_S0 = 8.0          # below this the analytic cap is useless anyway
CAP_HIT = [0, 0]      # [times the cap was binding, times it was DISJOINT]
SIGN_CLAMP = [0]      # times an I-constant's lower endpoint had to be
                      # clamped to 0 (header, honest limit (vii))
_CAP = {}


def prof_box_cap(nm, w, a):
    """Analytic caps on (Uhat, d_s Uhat) valid for EVERY s >= a >= 4, with
    Uhat := pad-profile(s)/s^2.  From Sec. 7b's  profile <= Ap/s  and
    |profile'| <= App/s:

        0 <= Uhat <= Ap/a^3,     |Uhat'| <= App/a^3 + 2 Ap/a^4.

    WHY THIS EXISTS.  A box (interval-s) profile evaluation over a WIDE cell
    at large s can fail badly -- the sigma-resonance band sigma ~ s is then
    itself interval-wide and the enclosure degrades without bound.  Feeding
    such a value into the Peano term  (w^2/8)*osc(h')  produced first-round
    relative slacks of 1e+02 (G) and 1e+54 (kappa).  Intersecting with this
    analytic cap removes that failure mode.  Both bounds are proved (Sec.
    7b), so the intersection is an enclosure of the same real set: it can
    only SHRINK the result, never move it.  The cap is ~1e4 lossy, so it is
    never binding where the numerical evaluation is healthy."""
    key = (nm, w, a)
    r = _CAP.get(key)
    if r is None:
        Ap, App = prof_tail_bounds(nm, w, a)
        A = iv.mpf(a)
        u = (Ap / A ** 3).b
        d = (App / A ** 3 + 2 * Ap / A ** 4).b
        r = (iv.mpf([0, u]), iv.mpf([-d, d]))
        _CAP[key] = r
    return r


def _apply_cap(nm, w, a, pair):
    """Intersect a (value, d_s value) profile pair with the analytic cap."""
    if a < CAP_S0:
        return pair
    cu, cd = prof_box_cap(nm, w, a)
    out = []
    for x, c in ((pair[0], cu), (pair[1], cd)):
        lo, hi = max(x.a, c.a), min(x.b, c.b)
        if lo > hi:                         # must not happen: soundness alarm
            CAP_HIT[1] += 1
            out.append(x)
            continue
        if hi < x.b or lo > x.a:
            CAP_HIT[0] += 1
        out.append(iv.mpf([lo, hi]))
    return (out[0], out[1])


_KINDS = ('W', 'GU')


def _cell_view(kind, a, b, pm, bx):
    """Per-cell interval data for one outer integrand.
    Returns (wi, hm, hpb, peano_iv, absrange_iv, sign).

    Peano midpoint rule with the ROUNDED midpoint accounted for.  Writing
    h' in [P,Q], c = (P+Q)/2, d = (Q-P)/2, m = (a+b)/2 exactly and m' the
    float actually used,

        | int_a^b h  -  w h(m') |  <=  |c| w |m-m'|  +  d ( w^2/4 + (m-m')^2 )

    since int_a^b (s-m') ds = w(m-m') and int_a^b |s-m'| ds = w^2/4 + (m-m')^2.
    The classical pad is the d w^2/4 term alone, which is exact ONLY when
    m' = m; m' = fl(0.5*(a+b)) misses on 226 of the 397 outer cells (worst
    displacement 6.07e-15 of a cell width), so the first and third terms are
    real, if tiny.  m-m' is enclosed by exact interval arithmetic rather than
    estimated.  The rule needs h merely Lipschitz -- no h'' -- which is why no
    higher-order rule is used: the outer integrand inherits only a Lipschitz
    certificate from the profile."""
    SB = iv.mpf([a, b])
    wi = iv.mpf(b) - iv.mpf(a)
    mfl = 0.5 * (a + b)
    hm, _ = _h_pair(kind, iv.mpf(mfl), pm[0], pm[1])
    _, hpb = _h_pair(kind, SB, bx[0], bx[1])
    # enclosure of the midpoint displacement e = m' - m
    E = iv.mpf(mfl) - (iv.mpf(a) + iv.mpf(b)) / 2
    ae = max(abs(mp.make_mpf(E._mpi_[0])), abs(mp.make_mpf(E._mpi_[1])))
    cmag = max(abs(mp.make_mpf(hpb._mpi_[0])), abs(mp.make_mpf(hpb._mpi_[1])))
    AE = iv.mpf(ae)
    dq = (hpb.b - hpb.a) / 2
    pe = ((wi ** 2) * (hpb.b - hpb.a) / 8
          + wi * AE * iv.mpf(cmag) + dq * AE ** 2).b
    sg = (1 if hpb.a > 0 else -1) if _definite(hpb) else 0
    lo, hi = _abs_range(hpb)
    return wi, hm, hpb, iv.mpf([-pe, pe]), iv.mpf([lo, hi]), sg


def cv_quad(nm, rel=1e-5, lo=OUTER_LO, top=OUTER_TOP, rho0=1.25,
            rel_pt=1e-10, rel_box=1e-2, maxc_pt=6000, maxc_box=2500,
            max_cells=30000, rounds=70, verbose=True):
    """The four pad constants of one family
    (W_nm, V_W_nm, GU_nm, V_GU_nm) as iv enclosures, plus diagnostics.

    `rel` is the target RELATIVE width of each of the four, enforced by
    equidistributing the per-cell Peano slack (for the two integrals) and
    the ambiguous-cell slack (for the two total variations)."""
    build_fam_sups(verbose=False)      # Sec. 7b tail majorant needs FAMSUP
    e = outer_edges(rho0, lo, top)     # same constructor the log header counts
    cells = [(e[i], e[i + 1]) for i in range(len(e) - 1)]
    B = e[-1]

    CE = {}        # (a,b) -> (pm, bx), each a (val_iv, der_iv) pair
    PT = {}        # s -> (val_iv, der_iv) at the POINT s
    VW = {}        # (kind, (a,b)) -> cached _cell_view
    t_ev = [0.0]

    def view(kind, ab):
        r = VW.get((kind, ab))
        if r is None:
            pm, bx = CE[ab]
            r = _cell_view(kind, ab[0], ab[1], pm, bx)
            VW[(kind, ab)] = r
        return r

    def evaluate(new):
        new = [ab for ab in new if ab not in CE]
        if not new:
            return
        jobs = []
        for (a, b) in new:
            jobs.append(('P', nm, 1, 0.5 * (a + b), rel_pt, maxc_pt))
            jobs.append(('B', nm, 1, a, b, rel_box, maxc_box))
        t0 = time.time()
        res = _pmap(jobs)
        t_ev[0] += time.time() - t0
        for i, ab in enumerate(new):
            m = 0.5 * (ab[0] + ab[1])
            pm = _apply_cap(nm, 1, m, res[2 * i])
            bx = _apply_cap(nm, 1, ab[0], res[2 * i + 1])
            CE[ab] = (pm, bx)
            PT[m] = pm

    def point(x):
        r = PT.get(x)
        if r is None:
            r = _apply_cap(nm, 1, x, _pmap([('P', nm, 1, x, rel_pt,
                                             maxc_pt)])[0])
            PT[x] = r
        return r

    evaluate(cells)

    # ---- adaptive refinement (float bookkeeping only) --------------------
    # `why` is set at the exit that actually fires, in the branch that
    # fires it.  Four exits plus the round cap; see EXITS above.
    nround = 0
    slack_rep = {}
    why = None
    for nround in range(1, rounds + 1):
        est = {k: 0.0 for k in _KINDS}
        sl = {k: 0.0 for k in _KINDS}
        vest = {k: 0.0 for k in _KINDS}
        vsl = {k: 0.0 for k in _KINDS}
        per = []
        for ab in cells:
            d = {}
            for k in _KINDS:
                wi, hm, hpb, pe, ar, sg = view(k, ab)
                ci = float((wi * hm).b)
                pw = float(pe.b)
                est[k] += abs(ci)
                sl[k] += pw
                vw = float((wi * (ar.b - ar.a)).b) if sg == 0 else 0.0
                vest[k] += float((wi * ar.b).b)
                vsl[k] += vw
                d[k] = (pw, vw)
            per.append(d)
        done = all(sl[k] <= rel * max(est[k], 1e-300) and
                   vsl[k] <= rel * max(vest[k], 1e-300) for k in _KINDS)
        slack_rep = {k: (sl[k] / max(est[k], 1e-300),
                         vsl[k] / max(vest[k], 1e-300)) for k in _KINDS}
        if verbose:
            log("     round %2d: cells=%5d  I-slack %s  V-slack %s"
                % (nround, len(cells),
                   " ".join("%s %.1e" % (k, slack_rep[k][0]) for k in _KINDS),
                   " ".join("%s %.1e" % (k, slack_rep[k][1]) for k in _KINDS)))
        if done or len(cells) >= max_cells:
            # Both can hold at once; report the tolerance in that case (the
            # width IS tolerance-set) but say so, since the cap is binding
            # for any further round.
            if done:
                why = 'tolerance met' + (
                    f' (cells={len(cells)} also >= cap {max_cells})'
                    if len(cells) >= max_cells else '')
            else:
                why = f'cell cap {max_cells}'
            break
        thr = {}
        for k in _KINDS:
            n_i = max(8, sum(1 for d in per if d[k][0] > 0))
            n_v = max(8, sum(1 for d in per if d[k][1] > 0))
            thr[k] = (0.3 * rel * max(est[k], 1e-300) / n_i,
                      0.3 * rel * max(vest[k], 1e-300) / n_v)
        cut = set()
        for i, d in enumerate(per):
            if any(d[k][0] > thr[k][0] or d[k][1] > thr[k][1] for k in _KINDS):
                cut.add(i)
        if not cut:
            # PROVABLY UNREACHABLE under the stated condition -- not merely
            # untested.  Condition: we are here only if `done` is False,
            # i.e. for some kind k, sl[k] > rel*E or vsl[k] > rel*VE with
            # E = max(est[k], 1e-300), VE = max(vest[k], 1e-300) -- the SAME
            # floored quantities `thr` is built from.  Take the I case:
            # sl[k] is a sum of c >= 1 positive pw's (c = 0 would give
            # sl[k] = 0, contradicting sl[k] > rel*E >= 0), n_i = max(8, c)
            # >= c, so max pw >= sl[k]/c >= sl[k]/n_i > rel*E/n_i, while
            # thr[k][0] = 0.3*rel*E/n_i.  The factor 1/0.3 = 3.3 of margin
            # absorbs float summation error (c <= 30000 terms, eps 1e-16).
            # Hence that cell is in `cut`.  Same for the V case.  Kept as a
            # branch and logged if it ever fires: the proof is about THIS
            # `thr`, and the next edit to it may invalidate the proof.
            why = 'no cell cut'
            break
        nc = []
        fresh = []
        for i, (a, b) in enumerate(cells):
            m = _split_pt(a, b) if i in cut else None
            if m is None or not (a < m < b):
                nc.append((a, b))
            else:
                nc.append((a, m))
                nc.append((m, b))
                fresh.append((a, m))
                fresh.append((m, b))
        if not fresh:
            why = 'no cell split'
            break
        evaluate(fresh)
        cells = nc
    else:
        why = f'round cap {rounds}'
    EXITS['cv:' + nm] = why
    if verbose:
        log(f"   {nm} cv exit: {why} after round {nround}, cells={len(cells)}")

    # ---- assemble (pure interval arithmetic; correct for ANY grid) -------
    # PARTITION, NOT COVER -- and therefore asserted, not merely argued.
    # cv_quad NEVER PRUNES: there is no running `best` and no discard.  Each
    # refinement round replaces a cell by either itself or its two halves
    # ((a,b) -> (a,m),(m,b) with a < m < b) and drops none, so `cells` is a
    # gapless, non-overlapping partition of [0, B] at every round and at
    # every one of the four exits (tolerance met / cell cap / no cell cut /
    # no cell split).  Hence EVERY exit costs width only, never soundness --
    # the same conclusion as tbar_bb's, but it does not follow from the same
    # invariant: tbar_bb takes a MAX over boxes, which tolerates overlap and
    # only needs a cover; cv_quad SUMS over cells and telescopes each
    # sign-definite run through cells[i][0]..cells[j][1], so a gap would
    # silently drop mass -- the integral, and with it the reported bound,
    # would come out TOO SMALL (fail-open) -- and an overlap would double
    # count.  A stronger invariant gets a check, not a comment.
    assert cells and cells[0][0] == 0.0 and cells[-1][1] == B, \
        (nm, cells[0], cells[-1], B)
    for _i in range(len(cells)):
        assert cells[_i][0] < cells[_i][1], (nm, _i, cells[_i])
        assert _i + 1 == len(cells) or cells[_i][1] == cells[_i + 1][0], \
            (nm, _i, cells[_i], cells[_i + 1])
    n = len(cells)
    out = {}
    info = {}
    marks = {}
    need = set()
    for k in _KINDS:
        sg = []
        for ab in cells:
            sg.append(view(k, ab)[5])
        marks[k] = sg
        i = 0
        while i < n:
            if sg[i] == 0:
                i += 1
                continue
            j = i
            while j + 1 < n and sg[j + 1] == sg[i]:
                j += 1
            need.add(cells[i][0])
            need.add(cells[j][1])
            i = j + 1
    need = sorted(x for x in need if x not in PT)
    if need:
        res = _pmap([('P', nm, 1, x, rel_pt, maxc_pt) for x in need])
        for x, r in zip(need, res):
            PT[x] = _apply_cap(nm, 1, x, r)

    for kind in _KINDS:
        sg = marks[kind]
        I_acc = iv.mpf(0)
        V_acc = iv.mpf(0)
        nam = 0
        nrun = 0
        for i, ab in enumerate(cells):
            wi, hm, hpb, pe, ar, _s = view(kind, ab)
            I_acc = I_acc + wi * hm + pe
            if sg[i] == 0:
                V_acc = V_acc + wi * ar
                nam += 1
        i = 0
        while i < n:
            if sg[i] == 0:
                i += 1
                continue
            j = i
            while j + 1 < n and sg[j + 1] == sg[i]:
                j += 1
            ha, _ = _h_pair(kind, iv.mpf(cells[i][0]), *PT[cells[i][0]])
            hb, _ = _h_pair(kind, iv.mpf(cells[j][1]), *PT[cells[j][1]])
            c = (hb - ha) if sg[i] > 0 else (ha - hb)
            v_lo = c.a if c.a > 0 else mp.mpf(0)
            V_acc = V_acc + iv.mpf([v_lo, c.b])
            nrun += 1
            i = j + 1
        # --- outer tail beyond B: the Sec. 7b analytic majorant ------------
        t0v, t1v = outer_tail(kind, nm, B)
        I_acc = I_acc + iv.mpf([0, t0v])
        V_acc = V_acc + iv.mpf([0, t1v])
        # Meet with [0, inf).  SOUND BECAUSE THE TRUTH LIES IN THE
        # INTERSECTION: it is in I_acc (interval arithmetic) and in [0, inf)
        # by the two proofs in header (vii) -- h_W = s^3 Uhat^2/2 >= 0 and
        # h_GU = G(s) s Uhat/2 >= 0 with G = 1/(1+s^2) > 0 by definition
        # and Uhat a total variation.  If either proof were wrong this line
        # would be unsound.  Needed because bounds3 takes iv.sqrt of
        # W_f + (D/2) V_W_f, which raises on a negative lower endpoint.
        # Counted, reported and checked by main().
        # `I_acc.a` is a DEGENERATE ivmpf vs an int: total order (R11).
        if I_acc.a < 0:
            SIGN_CLAMP[0] += 1
            I_acc = iv.mpf([0, I_acc.b])
        # The V-constant is >= 0 BY CONSTRUCTION (every summand above is:
        # per-run |.| clamped at 0, ambiguous cells w*[inf|h'|,sup|h'|],
        # tail [0, t1v]).  A proof that says "never binds" gets an ASSERT,
        # fail-closed, not a clamp: if this ever fires the construction
        # argument or the code is wrong and the run must stop.
        assert V_acc.a >= 0, (kind, nm, V_acc)
        key = kind + '_' + nm
        out[key] = I_acc
        out['V_' + key] = V_acc
        info[key] = QuadInfo(n, nrun, nam, float(t0v),
                             slack_rep.get(kind, (0.0, 0.0)), nround, why)
    if verbose:
        log("   %s: %d cells, %d profile evaluations (%.1fs)"
            % (nm, n, 2 * len(CE) + len(PT) - len(CE), t_ev[0]))
    return out, info


# ============================================================================
# SEC. 6.  THE 6 TBAR SUPS ON (0, S0]  --  INTERVAL BRANCH AND BOUND
# ============================================================================
# TBAR[nm]  = sup_{s>0} T_f(s),   TBAR['U'+nm] = sup_{s>0} U_f(s),
# with T_f(s) = s^2 * Uhat_{w=0}(s) and U_f(s) = s^2 * Uhat_{w=1}(s).
# prof_iv(nm, w, S) returns an enclosure valid for EVERY s in the interval S,
# so (S^2)*val is an enclosure of the RANGE of the profile over S: a textbook
# interval branch-and-bound applies, with no differentiability assumption and
# no grid-sup heuristic (M2 used a 4000-point grid times a safety factor 1.5;
# M3 added a further +20%).  Sec. 7 supplies the s > S0 majorant.
TBAR_S0 = 4096.0


def tbar_bb(nm, w, s0=TBAR_S0, rel=2e-3, rho0=1.35, max_boxes=900,
            rel_prof=3e-4, maxc=4000, verbose=False):
    """Rigorous sup of the pad profile over s in (0, s0]:  returns
    (sup_iv, nbox, neval).  sup_iv.b is the certified upper bound.

    TWO EXITS, ONE INVARIANT.  The loop leaves either by convergence
    (top <= lo_best*(1+rel)) or by the box cap (len(boxes) >= max_boxes).
    It never discards a box (`boxes = keep + new`), so the boxes cover
    (0, s0] at every round and `max hi` is a valid upper bound on EITHER
    exit; the cap exit costs tightness, not soundness.  Contrast
    `theta_star_certified`, which prunes and therefore genuinely depends on
    its lower bound being verified.  Observed: at the smoke setting
    (s0=64, rel=2e-1, rel_prof=2e-2) TBAR[kap] and TBAR[phi] both left by
    the cap, with [0.45343049, 2.50756953] and [0.47233251, 5.13818246] --
    uselessly wide, valid, as predicted.  Same 900 boxes and 1790 profile
    evaluations for both, but 1476.9 s vs 2660.5 s of wall clock: a box
    budget is not a time budget.  A cap exit at those tolerances says
    nothing about whether it fires at production tolerances; the run log
    records boxes= for each key."""
    ed = outer_edges(rho0, 1e-3, s0)   # same constructor the log header counts
    boxes = [(ed[i], ed[i + 1]) for i in range(len(ed) - 1)]
    hi = {}
    lo_best = mp.mpf(0)
    nev = [0]

    def ev(bs):
        jobs = [('B', nm, w, a, b, rel_prof, maxc) for (a, b) in bs]
        nev[0] += len(jobs)
        for (a, b), r in zip(bs, _pmap(jobs)):
            v = _apply_cap(nm, w, a, r)[0]
            # exact mp.mpf upper endpoint.  `.b` is a DEGENERATE ivmpf, and
            # `degenerate * (1 + rel)` below widens by an ulp, after which
            # `<=` can return None (falsy).  Same reason as theta_ub /
            # fam_sups: keep every comparison in this loop mpf-vs-mpf.
            hi[(a, b)] = mp.make_mpf((iv.mpf([a, b]) ** 2 * v)._mpi_[1])

    def low(pts):
        jobs = [('P', nm, w, x, rel_prof, maxc) for x in pts]
        nev[0] += len(jobs)
        out = mp.mpf(0)
        for x, r in zip(pts, _pmap(jobs)):
            v = _apply_cap(nm, w, x, r)[0]
            out = max(out, mp.make_mpf((iv.mpf(x) ** 2 * v)._mpi_[0]))
        return out

    ev(boxes)
    for _rd in range(40):
        boxes.sort(key=lambda ab: hi[ab], reverse=True)
        top = hi[boxes[0]]
        cand = [0.5 * (a + b) for (a, b) in boxes[:4]]
        lo_best = max(lo_best, low(cand))
        if verbose:
            log(f"   {nm} w={w} bb round {_rd}: boxes={len(boxes)} "
                f"hi={float(top):.8g} lo={float(lo_best):.8g}")
        if top <= lo_best * (1 + rel) or len(boxes) >= max_boxes:
            why = ("converged" if top <= lo_best * (1 + rel) else
                   f"box cap {max_boxes}")
            EXITS['tb:' + ('U' if w else '') + nm] = why
            if verbose:
                log(f"   {nm} w={w} bb exit: {why}"
                    f" after round {_rd}, boxes={len(boxes)}")
            break
        cut = [ab for ab in boxes if hi[ab] > lo_best * (1 + rel * 0.25)]
        cut = cut[:max(1, min(len(cut), max_boxes - len(boxes)))]
        keep = [ab for ab in boxes if ab not in set(cut)]
        new = []
        for (a, b) in cut:
            m = _split_pt(a, b) or 0.5 * (a + b)
            new += [(a, m), (m, b)]
        ev(new)
        boxes = keep + new
    else:
        # third exit: 40 rounds exhausted.  Same cover invariant, same
        # validity of max hi; logged so the three exits are distinguishable.
        EXITS['tb:' + ('U' if w else '') + nm] = "round cap 40"
        if verbose:
            log(f"   {nm} w={w} bb exit: round cap 40, boxes={len(boxes)}")
    top = max(hi[ab] for ab in boxes)
    return iv.mpf([lo_best, top]), len(boxes), nev[0]


# ============================================================================
# SEC. 7.  THE  s > S0  MAJORANT FOR THE PAD PROFILES  (fully analytic)
# ============================================================================
# This is the one place where a branch-and-bound cannot reach: the sup runs
# over the UNBOUNDED s-range.  M5 closes it by an elementary but completely
# rigorous two-step estimate.
#
# STEP 1 (a uniform bound on the NUMBER of monotone pieces).  Write
# eta = N/D with N(sigma) = s^2 sigma Nhat(sigma,s) (deg_sigma = K+1) and
# D(sigma) = 2 a^p A^p B^p g^(p+w) > 0 (deg_sigma = 6p+2w =: dD).  Then
#
#     eta'' = [ N'' D^2 - N D'' D - 2 D' N' D + 2 N (D')^2 ] / D^3 ,
#
# whose numerator is a polynomial in sigma of degree at most
#
#     d_f := K + 2 dD - 1 = K + 12 p + 4 w - 1
#
# (G: 13/17, kappa: 31/35, phi0: 49/53 for w = 0/1).  Hence eta'' has at
# most d_f zeros on (0,inf), psi := eta_sigma has at most d_f+1 monotone
# pieces there, and therefore
#
#     T_f(s) = TV_{(0,inf)}(psi) <= (d_f+1) * osc(psi)
#                                <= 2 (d_f+1) * sup_{sigma>0} |eta_sigma| .
#
# This bound is crude (it is off by ~20x at s = 4096) but it converts an
# integral sup into a POINTWISE sup, and that pointwise sup is elementary.
#
# STEP 2 (a pointwise bound).  With
#     M_k[f] := sup_{y in R} |f^(k)(y)| (1+y^2)     (k = 0..3),
#     g_k    := M_k[G],
# all six/four of which are rigorous 1-D interval sups (fam_sups() below),
# one has, for every s >= 4 and both w in {0,1},
#
#     sup_{sigma>0} |eta_sigma(sigma,s)|  <=  M_1/s + C_f/s^2,
#     C_f = 16 M_0 + M_1 + M_0 g_1/2
#           + (1/4 + g_1/8)(43/9 M_2 + 2 M_0 g_2)
#           + (1/12)       (43/9 M_3 + 2 M_0 g_3).
#
# Derivation (sigma >= 1).  eta = m(sigma) R, m = G^w/(2 sigma), so for
# sigma >= 1, w in {0,1}: |m| <= 1/(2 sigma), |m'| <= 2/sigma^2.  With
# R = f(s-sigma)+f(s+sigma)-2 f(s) G(sigma) - 2 delta f(sigma) G(s),
# delta <= 1, and |f^(k)(y)| <= M_k/(1+y^2):
#   (2/sigma^2)|R|      <= (8+2+4+2) M_0 / s^2                 = 16 M_0/s^2
#       [first term: if sigma >= s/2 then 2/sigma^2 <= 8/s^2; else
#        |s-sigma| >= s/2 so 1/(1+(s-sigma)^2) <= 4/s^2 and 2/sigma^2 <= 2]
#   (1/(2 sigma))|R'|   <= M_1/s + (M_1 + M_0 g_1/2)/s^2 .
# Derivation (0 < sigma <= 1).  eta = n(sigma) Q, n = G^w sigma/2,
# Q = R/sigma^2; |n| <= 1/2, |n'| <= 1/2 + g_1/4.  R is EVEN in sigma with
# R(0) = 0, hence R'(0) = 0 and
#     Q  = int_0^1 (1-t) R''(t sigma) dt,      |Q|  <= (1/2) sup|R''|,
#     Q' = int_0^1 (1-t) t R'''(t sigma) dt,   |Q'| <= (1/6) sup|R'''|,
# the sups over sigma in [0,1].  For s >= 4, (s-1)^2 >= (3s/4)^2, so
#     sup_{[0,1]}|R^(k)| <= (16/9 + 1 + 2) M_k/s^2 + 2 M_0 g_k/s^2
#                         = (43/9 M_k + 2 M_0 g_k)/s^2,  k = 2,3.
# Adding the two regions (which only over-counts) gives the display above.
#
# The final majorant is therefore
#
#     sup_{s >= S0} T_f(s)  <=  2 (d_f+1) ( M_1/S0 + C_f/S0^2 ),
#
# monotone decreasing in S0.  At S0 = 4096 this is ~7e-3 for every family,
# i.e. ~200x below the actual sup, so it never binds.
FAQ = {'G': (0, 1), 'kap': (2, 2), 'phi': (2, 3)}   # f = y^a/(1+y^2)^q


def _fam_bj_y(nm, Y):
    """BJ in x = y of f(y);  c[0..3] = f, f', f'', f'''."""
    a, q = FAQ[nm]
    two = iv.mpf(2)
    g = BJ.xonly(1 + Y ** 2, 2 * Y, two)
    num = BJ.xonly(Y ** 2, 2 * Y, two) if a == 2 else BJ.const(1)
    return num / (g ** q)


def _fam_bj_t(nm, T):
    """BJ in x = t of F(t) = f(1/t) = t^r/(1+t^2)^q,  r = 2q - a."""
    a, q = FAQ[nm]
    r = 2 * q - a
    two = iv.mpf(2)
    jt = BJ.xonly(T, _ONE)
    g = BJ.xonly(1 + T ** 2, 2 * T, two)
    return (jt ** r) / (g ** q)


def _fam_tail_hk(nm, T):
    """Upper bounds of  h_k(y) = |f^(k)(y)|(1+y^2)  for y = 1/t, t in T.
    With D := -t^2 d/dt (so f^(k)(1/t) = D^k F):
        f   = F,  f' = -t^2 F_t,  f'' = 2t^3 F_t + t^4 F_tt,
        f''' = -(6 t^4 F_t + 6 t^5 F_tt + t^6 F_ttt),
    and (1+y^2)/t^2 = (1+t^2)/t^4 .. all four products are regular at t = 0:
        h_0 = t^(r-2)/(1+t^2)^(q-1),        h_1 = |F_t| (1+t^2),
        h_2 = |2 t F_t + t^2 F_tt| (1+t^2), h_3 = |6 t^2 F_t + 6 t^3 F_tt
                                                  + t^4 F_ttt| (1+t^2)."""
    a, q = FAQ[nm]
    r = 2 * q - a
    F = _fam_bj_t(nm, T)
    f1, f2, f3 = F.c[1], F.c[2], F.c[3]
    one_t2 = 1 + T ** 2
    h0 = (T ** (r - 2) if r > 2 else _ONE) / (one_t2 ** (q - 1) if q > 1
                                              else _ONE)
    h1 = f1 * one_t2
    h2 = (2 * T * f1 + (T ** 2) * f2) * one_t2
    h3 = (6 * (T ** 2) * f1 + 6 * (T ** 3) * f2 + (T ** 4) * f3) * one_t2
    h4 = (24 * (T ** 3) * f1 + 36 * (T ** 4) * f2 + 12 * (T ** 5) * f3
          + (T ** 6) * F.c[4]) * one_t2
    return [_abs_range(z)[1] for z in (h0, h1, h2, h3, h4)]


def fam_sups(nm, y0=48.0, nb=4000, tol=1e-9):
    """Rigorous (M_0, ..., M_4) = sup_y |f^(k)(y)| (1+y^2), k = 0..4.
    Branch-and-bound on y in [0, y0] (f is even, so y >= 0 suffices) plus
    the compactified chart t = 1/y in [0, 1/y0] for y >= y0."""
    out = []
    # outward-rounded reciprocal -- see the note in `_sigma_tail`: `1.0 / y0`
    # rounds down for y0 = 48 and would leave a sliver above y0 in no chart.
    tl = _fam_tail_hk(nm, iv.mpf([0.0, (iv.mpf(1) / iv.mpf(y0)).b]))
    for k in range(5):
        # tail bound as an exact mp.mpf upper endpoint, used both as the
        # refinement threshold and in the final aggregation, so every
        # comparison in this loop is mp.mpf vs mp.mpf.
        tlk = mp.make_mpf(tl[k]._mpi_[1]) if hasattr(tl[k], '_mpi_') \
            else mp.mpf(tl[k])
        boxes = [(0.0, y0 * i / 24.0) if i == 1 else
                 (y0 * (i - 1) / 24.0, y0 * i / 24.0) for i in range(1, 25)]
        val = {}

        def up(ab):
            a, b = ab
            Y = iv.mpf([a, b])
            j = _fam_bj_y(nm, Y)
            # exact mp.mpf endpoints -- see the note in theta_ub on `ivmpf >
            # mpf` returning None for an overlapping interval.  Like tbar_bb
            # (and unlike theta_star_certified) this loop never DISCARDS a
            # box -- `keep` retains everything not cut and each cut box is
            # replaced by both halves -- so a falsy comparison here would cost
            # tightness rather than soundness.  Made exact anyway: the reader
            # should not have to re-derive which of the three is which.
            return mp.make_mpf(
                (_abs_range(j.c[k])[1] * (1 + iv.mpf(b) ** 2))._mpi_[1])
        for ab in boxes:
            val[ab] = up(ab)
        best = tlk
        for _rd in range(60):
            boxes.sort(key=lambda ab: val[ab], reverse=True)
            top = val[boxes[0]]
            a, b = boxes[0]
            mid = 0.5 * (a + b)
            j = _fam_bj_y(nm, iv.mpf(mid))
            best = max(best, mp.make_mpf(
                (_abs_range(j.c[k])[1] * (1 + iv.mpf(mid) ** 2))._mpi_[0]))
            if top <= best * (1 + tol) or len(boxes) >= nb:
                break
            cut = [ab for ab in boxes if val[ab] > best * (1 + tol * 0.25)]
            cut = cut[:max(1, min(len(cut), nb - len(boxes)))]
            keep = [ab for ab in boxes if ab not in set(cut)]
            new = []
            for (a, b) in cut:
                m = 0.5 * (a + b)
                new += [(a, m), (m, b)]
            for ab in new:
                val[ab] = up(ab)
            boxes = keep + new
        # Back to a DEGENERATE ivmpf on the way out.  `up()` and `tlk` are
        # exact mp.mpf only so that the comparisons INSIDE this loop are
        # mpf-vs-mpf; the result must stay an interval type, because every
        # consumer (tbar_tail_bound, prof_tail_bounds) feeds M_k straight
        # into interval arithmetic.  Returning a bare mp.mpf would make
        # products like `M[0] * g[1] / 2` round to NEAREST in the mp context
        # instead of outward -- silently non-rigorous.
        out.append(_iv_pt(max(max(val[ab] for ab in boxes), tlk)))
    return out


FAMSUP = {}


def build_fam_sups(verbose=True):
    if FAMSUP:
        return
    t0 = time.time()
    for nm in ('G', 'kap', 'phi'):
        FAMSUP[nm] = fam_sups(nm)
    if verbose:
        for nm in ('G', 'kap', 'phi'):
            log("   M_k[%-3s] = %s" % (nm, ["%.6f" % float(v)
                                            for v in FAMSUP[nm]]))
        log(f"   family sups built ({time.time()-t0:.1f}s)")


def deg_bound(nm, w):
    """d_f = K + 12 p + 4 w - 1  >=  #zeros of eta_sigmasigma on (0,inf)."""
    return KDEG[nm] + 12 * PPOW[nm] + 4 * w - 1


def tbar_tail_bound(nm, w, s0=TBAR_S0):
    """Rigorous  sup_{s >= s0} (pad profile)  --  Sec. 7, steps 1 and 2."""
    assert s0 >= 4.0
    build_fam_sups(verbose=False)
    M = FAMSUP[nm]
    g = FAMSUP['G']
    S = iv.mpf(s0)
    c43 = iv.mpf(43) / 9
    C = (16 * M[0] + M[1] + M[0] * g[1] / 2
         + (iv.mpf(1) / 4 + g[1] / 8) * (c43 * M[2] + 2 * M[0] * g[2])
         + (iv.mpf(1) / 12) * (c43 * M[3] + 2 * M[0] * g[3]))
    sup_eta_s = M[1] / S + C / (S ** 2)
    return (2 * (deg_bound(nm, w) + 1) * sup_eta_s).b


# ---------------------------------------------------------------------------
# SEC. 7b.  THE SAME MACHINERY APPLIED TO  d_s eta  ->  THE OUTER s-TAIL
# ---------------------------------------------------------------------------
# M3 and M4 bound every outer tail by the inherited rule 10*B*sup|h([B,3B])|,
# which assumes polynomial decay.  M5 does NOT need it: rho := d_s eta has
# exactly the same structure as eta, so Steps 1-2 of Sec. 7 apply verbatim
# and give a rigorous bound on |U_f'| as well.
#
# STEP 1'.  rho = d_s(N/D) = (N_s D - N D_s)/D^2 has sigma-numerator degree
# <= (K+1) + dD, over D^2 of degree 2 dD, so the numerator of rho'' has
# sigma-degree at most
#     d'_f := K + 5 dD - 1 = K + 30 p + 10 w - 1 ,
# and  |U_f'(s)| <= int |rho_sigmasigma| dsigma = TV_sigma(rho_sigma)
#                <= 2 (d'_f+1) sup_sigma |rho_sigma| .
#
# STEP 2'.  rho = m(sigma) R_s with
#     R_s     = f'(s-sigma) + f'(s+sigma) - 2 f'(s) G - 2 delta f G'(s),
#     R_ssigma= -f''(s-sigma)+ f''(s+sigma)- 2 f'(s) G' - 2 delta f' G'(s),
# R_s is again EVEN in sigma with R_s(0) = 0 (f(0) = 0 whenever delta = 1),
# so the sigma <= 1 treatment is identical.  The same four estimates give,
# for s >= 4,
#     sup_sigma |rho_sigma| <= M_2/s + C'_f/s^2,
#     C'_f = 12 M_1 + 2 M_0 g_1 + M_2/2 + M_1 g_1
#            + (1/4 + g_1/8)(25/9 M_3 + 2 M_1 g_2 + 2 M_2 g_1)
#            + (1/12)       (25/9 M_4 + 2 M_1 g_3 + 2 M_3 g_1).
#
# Consequently, for every s >= B >= max(4, S0),
#     U_f(s)   <= Ap/s,   Ap  := 2(d_f +1)(M_1 + C_f /B),
#     |U_f'(s)|<= App/s,  App := 2(d'_f+1)(M_2 + C'_f/B),
# and with h_W = U^2/(2s), h_GU = G(s) U/(2s), G(s) <= 1/s^2:
#     int_B^inf h_W    <= Ap^2/(4 B^2)
#     int_B^inf |h_W'| <= Ap App/(2 B^2) + Ap^2/(6 B^3)
#     int_B^inf h_GU   <= Ap/(6 B^3)
#     int_B^inf |h_GU'|<= (Ap + App)/(6 B^3) + Ap/(8 B^4)
# (using |h_W'| <= |U U'|/s + U^2/(2 s^2) and
#  |h_GU'| <= |G'| U/(2s) + G |U'|/(2s) + G U/(2 s^2), |G'(s)| <= 1/s^2).
# No decay assumption is made anywhere, so M3/M4's honest limit (i) is
# CLOSED in M5.
def deg_bound_s(nm, w):
    """d'_f = K + 30 p + 10 w - 1  >=  #zeros of d_s eta_sigmasigma."""
    return KDEG[nm] + 30 * PPOW[nm] + 10 * w - 1


def prof_tail_bounds(nm, w, B):
    """(Ap, App):  pad profile <= Ap/s  and  |d/ds pad profile| <= App/s
    for every s >= B.   Both are iv upper bounds."""
    assert B >= 4.0
    build_fam_sups(verbose=False)
    M = FAMSUP[nm]
    g = FAMSUP['G']
    S = iv.mpf(B)
    c43 = iv.mpf(43) / 9
    c25 = iv.mpf(25) / 9
    q1 = iv.mpf(1) / 4 + g[1] / 8
    q2 = iv.mpf(1) / 12
    C = (16 * M[0] + M[1] + M[0] * g[1] / 2
         + q1 * (c43 * M[2] + 2 * M[0] * g[2])
         + q2 * (c43 * M[3] + 2 * M[0] * g[3]))
    Cp = (12 * M[1] + 2 * M[0] * g[1] + M[2] / 2 + M[1] * g[1]
          + q1 * (c25 * M[3] + 2 * M[1] * g[2] + 2 * M[2] * g[1])
          + q2 * (c25 * M[4] + 2 * M[1] * g[3] + 2 * M[3] * g[1]))
    Ap = 2 * (deg_bound(nm, w) + 1) * (M[1] + C / S)
    App = 2 * (deg_bound_s(nm, w) + 1) * (M[2] + Cp / S)
    return iv.mpf([0, Ap.b]), iv.mpf([0, App.b])


def outer_tail(kind, nm, B):
    """Rigorous (int_B^inf h, int_B^inf |h'|) upper bounds, w = 1."""
    Ap, App = prof_tail_bounds(nm, 1, B)
    S = iv.mpf(B)
    if kind == 'W':
        I = (Ap ** 2) / (4 * S ** 2)
        V = Ap * App / (2 * S ** 2) + (Ap ** 2) / (6 * S ** 3)
    else:
        I = Ap / (6 * S ** 3)
        V = (Ap + App) / (6 * S ** 3) + Ap / (8 * S ** 4)
    return I.b, V.b



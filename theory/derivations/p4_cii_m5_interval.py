PREC_REF = 700          # bits for the external reference


def _lohi(z):
    """Exact endpoints of an ivmpf as mp.mpf (works at any ambient prec)."""
    return mp.make_mpf(z._mpi_[0]), mp.make_mpf(z._mpi_[1])


def _contains0(z):
    return z.a <= 0 <= z.b


# ---- exact rational anchors: no transcendental, no library, no float ------
# The three arctan identities below (complementary-angle, double-angle,
# Machin) are all HOMOGENEOUS OF DEGREE 1 in atan, and PI_IV is itself built
# from iv_atan_nn.  The whole set is therefore invariant under atan -> C*atan
# and is STRUCTURALLY BLIND to a wrong scale-back factor `2**k`: a mutant that
# doubles every result passes all three.  Measured, not feared -- mutating
# line `return s * (2 ** k)` to `2 ** (k+1)` leaves every identity green.
# (Found by the segment C-I agent on its own arctan and confirmed here on
# this one; two independently written implementations, both scale directions.)
#
# The repair is an ABSOLUTE anchor that is not homogeneous.  For 0 < u < 1 the
# arctan series alternates with strictly decreasing terms, so consecutive
# partial sums bracket the value; with the first three terms
#
#       u - u^3/3  <  atan u  <  u - u^3/3 + u^5/5 ,
#
# both ends rational.  Anchors are DYADIC (so u is represented exactly) and
# lie ABOVE the 1/16 halving threshold, so the halving loop, the series and
# the scale-back are pinned TOGETHER.  Four of them, spanning halving depths
# 4/3/2/1, because a mutant that is correct at shallow reduction and wrong
# only at deep reduction survives a single anchor.
_ANCHORS = ((3, 4), (1, 2), (1, 4), (1, 8))


def _dyadic(x):
    """Exact (num, den) of an mp.mpf; den is a power of two.  Reads the
    mantissa/exponent straight off `_mpf_` -- raw data, not a computation."""
    sign, man, exp, _bc = x._mpf_
    m = -man if sign else man
    return (m << exp, 1) if exp >= 0 else (m, 1 << (-exp))


def _cmp_ratio(x, num, den):
    """sign(x - num/den) for an mp.mpf x and integers num, den>0, by INTEGER
    arithmetic only -- no floating point on either side of the comparison."""
    n, d = _dyadic(x)
    left, right = n * den, num * d
    return (left > right) - (left < right)


def _atan_bracket(p, q, nterms=2):
    """Exact rational (lo, hi) with lo < atan(p/q) < hi, from two consecutive
    partial sums of the alternating series.  Requires 0 < p/q < 1."""
    assert 0 < Fraction(p, q) < 1, (p, q)
    s = Fraction(0)
    u = Fraction(p, q)
    for j in range(nterms):
        s += Fraction((-1) ** j, 2 * j + 1) * u ** (2 * j + 1)
    nxt = s + Fraction((-1) ** nterms, 2 * nterms + 1) * u ** (2 * nterms + 1)
    return (s, nxt) if s < nxt else (nxt, s)


def _series_partial(p, q, n):
    """Exact partial sum sum_{j<n} (-1)^j u^(2j+1)/(2j+1), u = p/q."""
    u = Fraction(p, q)
    return sum((Fraction((-1) ** j, 2 * j + 1) * u ** (2 * j + 1)
                for j in range(n)), Fraction(0))


def _pi_bracket(nterms=12):
    """Exact rational bracket for pi from Machin, pi = 16 atan(1/5) -
    4 atan(1/239), each arctan bracketed by consecutive partial sums.  Used
    so the PI_IV check has a reference that is NOT its own defining
    expression."""
    a_lo, a_hi = _atan_bracket(1, 5, nterms)
    b_lo, b_hi = _atan_bracket(1, 239, nterms)
    return 16 * a_lo - 4 * b_hi, 16 * a_hi - 4 * b_lo


def _atan_operands():
    """A fixed, reproducible operand set: dyadic, decimal, near the halving
    thresholds, tiny, huge, and a pseudo-random sweep from a FIXED seed."""
    rnd = random.Random(20260912)
    xs = [0.0, 1.0, 0.5, 0.0625, 0.06250000001, 2.0, 1e-18, 1e18,
          0.41421356237309515, 0.9999999, 1.0000001, 5.0, 239.0, 1.0 / 5,
          1.0 / 239]
    xs += [mp.mpf(k) / 997 for k in range(1, 400)]
    xs += [rnd.uniform(-300.0, 300.0) for _ in range(1500)]
    xs += [rnd.uniform(-1e-5, 1e-5) for _ in range(300)]
    xs += [rnd.uniform(-1e9, 1e9) for _ in range(300)]
    return xs


def _ref_miss(fn, xs):
    """How many operands the interval routine `fn` FAILS to enclose, against
    a PREC_REF-bit mp.atan.  Returns (misses, worst absolute excursion)."""
    bad, worst = 0, mp.mpf(0)
    for x in xs:
        try:
            z = fn(iv.mpf(x))
        except Exception:
            bad += 1
            continue
        lo, hi = _lohi(z)
        with mp.workprec(PREC_REF):
            t = mp.atan(mp.mpf(x))
        if t < lo or t > hi:
            bad += 1
            worst = max(worst, max(lo - t, t - hi))
    return bad, worst


def check_certified_atan():
    """Two independent kinds of evidence for `iv_atan`.

    (A) RIGOROUS self-consistency: four arctan identities, each asserted as a
        genuine interval containment (the difference must CONTAIN zero), using
        `iv_atan_nn` only against itself.  They appeal to no external value at
        all.  What they do NOT pin, and an earlier version of this docstring
        wrongly claimed they did, is the scale and the remainder pad:

          - all three identities are HOMOGENEOUS OF DEGREE 1 in atan and
            PI_IV is built from iv_atan_nn, so the set is invariant under
            atan -> C*atan.  Mutating the scale-back `2**k` to `2**(k+1)`
            leaves every identity green; and
          - cutting _ATAN_N from 20 to 8 is caught only by the width check,
            while deleting the remainder pad outright is caught by nothing at
            all, because at nterms=20 the truncation is ~3e-52 against a
            prec-103 rounding width ~1e-31.

        (A2) and (A3) below repair exactly those two blind spots, with an
        absolute rational anchor and a small-nterms pad test.  The identities
        are kept: they are what catches the sqrt, the denominators and the
        term count.  The general lesson, worth more than the instance: first
        ask what group your validation set is invariant under, then ask what
        it can detect.  (Blind spot found by the segment C-I agent on its own
        arctan; reproduced here on this one, in both scale directions.)

    (B) EVIDENCE against a PREC_REF-bit reference, with a NEGATIVE CONTROL:
        `iv.atan2` must FAIL the very same test.  Without the control a clean
        pass would be consistent with a vacuous test (e.g. a reference that is
        itself only nearest-rounded at working precision), which is exactly
        the failure mode that produced this session's false `iv.pi` alarm.
        Keep this tier even though (A2) now covers the scale: until (A2)
        existed, this reference test was carrying the scale claim ALONE, in a
        module whose entire purpose is not to trust mpmath's transcendentals.

    The two implementations being cross-checked here are independent: mine
    (Horner evaluation of the alternating series, general intervals handled by
    monotonicity through the endpoints) and the segment C-I module's (forward
    power accumulation, nonnegative arguments only).  They agree on the scheme
    -- half-angle reduction to <= 1/16, then 20 terms with the alternating-
    series remainder as a two-sided pad -- which was arrived at separately on
    both sides.  That agreement is evidence BECAUSE the implementations were
    written before contact, not after."""
    print("\n=== certified arctan ===")
    # -- (A) rigorous identities ------------------------------------------
    half_pi = PI_IV / 2
    ok = True
    for t in ('0.1', '0.5', '1', '2', '7', '137', '1e6'):
        T = iv.mpf(t)
        ok &= _contains0(iv_atan_nn(T) + iv_atan_nn(1 / T) - half_pi)
    chk("identity  atan t + atan(1/t) = pi/2  (7 scales, contains 0)", ok)
    ok = True
    for t in ('0.03125', '0.1', '0.25', '0.4'):
        T = iv.mpf(t)
        ok &= _contains0(iv_atan_nn(2 * T / (1 - T ** 2)) - 2 * iv_atan_nn(T))
    chk("identity  atan(2t/(1-t^2)) = 2 atan t  (4 scales, contains 0)", ok)
    machin = 16 * iv_atan_nn(iv.mpf(1) / 5) - 4 * iv_atan_nn(iv.mpf(1) / 239)
    chk("identity  Machin 16 atan(1/5) - 4 atan(1/239) = pi",
        _contains0(machin - PI_IV),
        f"width {float(machin.b - machin.a):.2e}")
    ok = True
    for t in ('1e-9', '0.3', '1', '4', '1e4'):
        z = iv_atan_nn(iv.mpf(t))
        ok &= float(z.b - z.a) <= 1e-27 * max(float(z.b), 1e-30)
    chk("returned relative width <= 1e-27 (5 scales)", ok)
    # monotone extension to sign-straddling intervals
    ok = True
    for (a, b) in ((-5.0, 5.0), (-1e-9, 1e-9), (0.0, 1e6), (-1e7, -3.0)):
        z = iv_atan(iv.mpf([a, b]))
        with mp.workprec(PREC_REF):
            ta, tb = mp.atan(mp.mpf(a)), mp.atan(mp.mpf(b))
        lo, hi = _lohi(z)
        ok &= (lo <= ta and tb <= hi)
    chk("iv_atan encloses both endpoints on sign-straddling intervals", ok)
    # -- (A2) ABSOLUTE rational anchors: these are what pin the SCALE -------
    ok, worst = True, None
    for (p, q) in _ANCHORS:
        u = iv.mpf(p) / q                    # dyadic: exact, degenerate
        assert u._mpi_[0] == u._mpi_[1] and _cmp_ratio(
            mp.make_mpf(u._mpi_[0]), p, q) == 0, (p, q)
        lo, hi = _atan_bracket(p, q)
        z = iv_atan_nn(u)
        za, zb = _lohi(z)
        good = (_cmp_ratio(za, lo.numerator, lo.denominator) >= 0 and
                _cmp_ratio(zb, hi.numerator, hi.denominator) <= 0)
        ok &= good
        if worst is None:
            worst = float(hi - lo)
    chk("ABSOLUTE anchor  u - u^3/3 < atan u < u - u^3/3 + u^5/5  "
        "(4 dyadic u, halving depths 4/3/2/1, exact integer comparison)", ok,
        f"tightest bracket {float(_atan_bracket(1, 8)[1] - _atan_bracket(1, 8)[0]):.2e} "
        f"vs a certified width ~1e-30")
    # negative control: the anchor must REJECT a deliberately rescaled arctan,
    # or it is no better than the homogeneous identities it was added to fix.
    fires = 0
    for (p, q) in _ANCHORS:
        lo, hi = _atan_bracket(p, q)
        for factor in (2, mp.mpf(1) / 2):
            z = iv_atan_nn(iv.mpf(p) / q) * factor
            za, zb = _lohi(z)
            if not (_cmp_ratio(za, lo.numerator, lo.denominator) >= 0 and
                    _cmp_ratio(zb, hi.numerator, hi.denominator) <= 0):
                fires += 1
    chk("NEGATIVE CONTROL: the anchor rejects atan scaled by 2 and by 1/2 "
        "(the identities do not)", fires == 2 * len(_ANCHORS),
        f"{fires}/{2*len(_ANCHORS)} rejected")
    # -- (A3) the remainder pad, at a term count where it is RESOLVABLE ----
    # At _ATAN_N = 20 the truncation is ~3e-52, below one ulp at prec 103, so
    # deleting the pad entirely moves no endpoint bit and NO check on the
    # shipped configuration can see it.  Driving the same code at small
    # nterms makes the pad the dominant term.  The reference is the exact
    # rational bracket [S_n, S_{n+1}] -- the alternating-series theorem itself
    # -- so this needs no transcendental and no library arctan.
    ok, seen = True, 0
    for n in (1, 2, 3, 4, 5):
        for (p, q) in ((1, 16), (1, 32), (3, 64), (1, 128), (5, 256)):
            z = iv_atan_nn(iv.mpf(p) / q, nterms=n)
            za, zb = _lohi(z)
            s_n = _series_partial(p, q, n)
            s_n1 = _series_partial(p, q, n + 1)
            lo, hi = (s_n, s_n1) if s_n < s_n1 else (s_n1, s_n)
            ok &= (_cmp_ratio(za, lo.numerator, lo.denominator) <= 0 and
                   _cmp_ratio(zb, hi.numerator, hi.denominator) >= 0)
            seen += 1
    chk("the alternating-series remainder pad is two-sided and dominates the "
        "truncation (25 cases at nterms 1..5, exact rational bracket)", ok,
        f"{seen} cases; deleting or one-siding `rem` breaks these, "
        f"while at nterms=20 it changes no bit")
    # -- (A4) PI_IV against a reference that is NOT its own definition ------
    plo, phi = _pi_bracket()
    pa, pb = _lohi(PI_IV)
    chk("PI_IV encloses pi, vs an EXACT-RATIONAL Machin bracket "
        "(not PI_IV's own defining expression)",
        _cmp_ratio(pa, plo.numerator, plo.denominator) >= 0 and
        _cmp_ratio(pb, phi.numerator, phi.denominator) <= 0,
        f"rational bracket width {float(phi - plo):.2e}, PI_IV width "
        f"{float(pb - pa):.2e}")
    # -- (B) reference + negative control ---------------------------------
    xs = _atan_operands()
    with mp.workprec(PREC_REF):
        _probe = mp.atan(mp.mpf(3) / 7)
    chk(f"the {PREC_REF}-bit reference really is high precision",
        _probe._mpf_[3] > 500, f"{_probe._mpf_[3]} mantissa bits")
    bad, worst = _ref_miss(iv_atan, xs)
    chk(f"iv_atan encloses mp.atan on all {len(xs)} operands", bad == 0,
        f"{bad} misses, worst excursion {float(worst):.3e}")
    bad2, worst2 = _ref_miss(lambda z: iv.atan2(z, iv.mpf(1)), xs)
    chk("NEGATIVE CONTROL: iv.atan2 fails that same test (else it is vacuous)",
        bad2 > 0,
        f"{bad2}/{len(xs)} misses, worst excursion {float(worst2):.3e}")


def check_theta_star():
    """The certified Theta* must (i) enclose a high-precision Theta*, (ii) be
    an upper bound for Theta on a dense grid, and (iii) be compared against
    what M3 shipped.  M3's own check `contains(THETA_STAR_IV, M2.THETA_STAR)`
    could never catch this: M2's value is another float64 evaluation of the
    same quantity, so the two agree to the last bit of a float and the check
    passes vacuously."""
    print("\n=== certified Theta* ===")
    with mp.workprec(PREC_REF):
        def N(s):
            return 2 * s + (1 - s * s) * mp.atan(s) - s * mp.log(1 + s * s)
        a, b = mp.mpf(1), mp.mpf(2)
        for _ in range(PREC_REF + 20):
            m = (a + b) / 2
            if N(m) > 0:
                a = m
            else:
                b = m
        sstar = (a + b) / 2
        ts = ((mp.log(1 + sstar ** 2) + 2 * sstar * mp.atan(sstar))
              / (2 * (1 + sstar ** 2)))
        grid = [mp.mpf(k) / 64 for k in range(1, 64 * 40)]
        vals = [(mp.log(1 + s ** 2) + 2 * s * mp.atan(s)) / (2 * (1 + s ** 2))
                for s in grid]
    new, arg = theta_star_certified()
    nlo, nhi = _lohi(new)
    chk("certified Theta* encloses the %d-bit maximum" % PREC_REF,
        nlo <= ts <= nhi,
        f"[{mp.nstr(nlo, 25)}, {mp.nstr(nhi, 25)}]  width "
        f"{float(nhi - nlo):.2e}  argmax ~ {arg:.10f}")
    chk("certified Theta*.hi dominates Theta on a 2560-point grid",
        all(v <= nhi for v in vals))
    old, _ = _M3_THETA_STAR_ORIG()
    olo, ohi = _lohi(old)
    chk("REGRESSION WITNESS: M3's original theta_star_iv did NOT enclose",
        not (olo <= ts <= ohi),
        f"M3 = [{mp.nstr(olo, 25)}, {mp.nstr(ohi, 25)}] (width "
        f"{float(ohi - olo):.1e}); true Theta* = {mp.nstr(ts, 25)}; "
        f"true - M3.hi = {float(ts - ohi):+.6e} -> M3.hi lies BELOW the true "
        f"maximum, and Theta* enters bounds3 as an UPPER bound, so the "
        f"direction is unsafe")
    return old, new


